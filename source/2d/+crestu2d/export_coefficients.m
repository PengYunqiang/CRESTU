function data=export_coefficients(result,filename)
%EXPORT_COEFFICIENTS Portable full matrices and explicit complex JSON values.
% One record per frequency avoids singleton-dimension JSON ambiguity.
    ids=result.input.dof_indices;
    data=struct('schema','CRESTU-2D-COEFFICIENTS-1','module_version',result.module_version, ...
        'name',result.name,'dofs',{result.dofs},'matrix_order','force_row_motion_column', ...
        'phase',result.phase,'coordinates',result.input.coordinates, ...
        'reference_yz_m',result.reference_yz_m,'waterline_z_m',result.input.waterline_z_m, ...
        'physical_model',result.input.fluid.domain,'water_depth_m',result.input.fluid.depth_m, ...
        'normalization_length_m',result.input.normalization_length_m,'normalization',result.normalization, ...
        'rho_kg_m3',result.input.fluid.rho_kg_m3,'g_m_s2',result.input.fluid.g_m_s2, ...
        'solver',result.input.solver,'radiation_normalization',result.radiation_normalization, ...
        'units',struct('A',{result.units.A(ids,ids)},'B',{result.units.B(ids,ids)}, ...
            'F_exc',{result.units.F_exc(ids)},'F_per_amplitude',{result.units.F_exc_per_amplitude(ids)}), ...
        'load_scope','per unit longitudinal length; no strip integration', ...
        'complex_encoding','Explicit real/imaginary arrays; exp(+i*omega*t).', ...
        'metadata',result.metadata,'frequencies',struct([]));
    % MATLAB encodes a cell matrix as a column-major JSON list. Supply an
    % explicit DOF mapping as the authoritative interchange unit contract.
    data.units.matrix_storage_order='column_major';
    unitEntries=struct([]);index=0;
    for i=1:numel(ids)
        for j=1:numel(ids)
            index=index+1;item=struct('row',i,'column',j,'force_dof',result.dofs{i}, ...
                'motion_dof',result.dofs{j},'A',result.units.A{ids(i),ids(j)},'B',result.units.B{ids(i),ids(j)});
            if index==1,unitEntries=item;else,unitEntries(index)=item;end %#ok<AGROW>
        end
    end
    data.unit_entries=unitEntries;
    for f=1:numel(result.omega_rad_s)
        record=struct('omega_rad_s',result.omega_rad_s(f),'k_m_inv',result.diagnostics(f).k_m_inv, ...
            'A',result.A(:,:,f),'B',result.B(:,:,f), ...
            'A_hat',result.A_hat(:,:,f),'B_hat',result.B_hat(:,:,f), ...
            'F_exc',struct('real',[],'imag',[]),'F_per_amplitude',struct('real',[],'imag',[]), ...
            'FK_per_amplitude',struct('real',[],'imag',[]));
        if ~isempty(result.F_exc_per_amplitude)
            record.F_exc=parts(result.F_exc(:,f));record.F_per_amplitude=parts(result.F_exc_per_amplitude(:,f));
            record.FK_per_amplitude=parts(result.F_FK_per_amplitude(:,f));
        end
        if f==1,data.frequencies=record;else,data.frequencies(f)=record;end
    end
    fid=fopen(filename,'w','n','UTF-8');assert(fid>=0,'CRESTU2D:Output','Cannot write coefficients JSON.');
    closeFile=onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s\n',jsonencode(data,PrettyPrint=true));
end
function value=parts(z),value=struct('real',real(z),'imag',imag(z));end
