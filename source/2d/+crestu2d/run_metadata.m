function metadata=run_metadata(root,cfg)
%RUN_METADATA Record execution provenance without changing numerical inputs.
    metadata=struct('schema','CRESTU-2D-RUN-METADATA-1', ...
        'started_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ss.SSS''Z''')), ...
        'matlab_version',version,'matlab_release',version('-release'), ...
        'platform',computer,'phase',cfg.phase,'coordinates',cfg.coordinates, ...
        'reference_yz_m',cfg.reference_yz_m,'dofs',{cfg.dofs}, ...
        'physical_model',cfg.fluid.domain,'water_depth_m',cfg.fluid.depth_m, ...
        'solver_method',cfg.solver.method,'augmentation',cfg.solver.augmentation, ...
        'normalization_length_m',cfg.normalization_length_m,'omega_rad_s',cfg.omega_rad_s, ...
        'numerical_version','0.3-research','module_version','0.4.0-rc1', ...
        'independent_validation_status','Consult README.md for the validation scope of this package.', ...
        'output_directory',cfg.output.directory,'save_requested',cfg.output.save, ...
        'timing_scope','Provenance capture and numerical solve; excludes result export.');
    if isfield(cfg,'input_file'), metadata.input_file=cfg.input_file; end
    source=struct('root',root,'status','UNAVAILABLE','commit','', ...
        'dirty',[],'changes',{{}}, ...
        'checked_paths',{{'CRESTU_SETUP.m','CRESTU_2D.m','CRESTU_2D_BATCH.m','CRESTU_2D_HF.m','source/2d','research/p2_hf'}}, ...
        'note','HEAD identifies the base commit. A dirty tree may contain changes to the entries, solver or validation files.');
    [headCode,head]=system(sprintf('git -C "%s" rev-parse HEAD 2>&1',root));
    if headCode==0
        source.commit=strtrim(head);
        [statusCode,status]=system(sprintf(['git -C "%s" status --porcelain --untracked-files=all -- ', ...
            'CRESTU_SETUP.m CRESTU_2D.m CRESTU_2D_BATCH.m CRESTU_2D_HF.m "source/2d" "research/p2_hf" 2>&1'],root));
        if statusCode==0
            source.status='RECORDED_AT_RUN_START';
            source.dirty=~isempty(strtrim(status));
            if source.dirty,source.changes=regexp(strtrim(status),'\r?\n','split');end
        else
            source.message=strtrim(status);
        end
    else
        source.message=strtrim(head);
    end
    metadata.source=source;
end
