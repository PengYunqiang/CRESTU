function result=solve_finite(cfg)
%SOLVE_FINITE Public result adapter for a distinct finite-depth boundary model.
% The direct formulation stores boundary phi/q, not fictitious source strengths.
    geo=crestu2d.geometry(cfg);ids=cfg.dof_indices;nd=numel(ids);nf=numel(cfg.omega_rad_s);
    rho=cfg.fluid.rho_kg_m3;g=cfg.fluid.g_m_s2;L=cfg.normalization_length_m;
    diffraction=strcmp(cfg.problem,'radiation_diffraction');
    nodes=geo.nodes;nodes(:,2)=nodes(:,2)-cfg.waterline_z_m;
    ref=cfg.reference_yz_m;ref(2)=ref(2)-cfg.waterline_z_m;
    opt=struct('rho',rho,'g',g,'depth',cfg.fluid.depth_m,'side',cfg.solver.side_extent_m, ...
        'reference',ref,'normalization_length',L,'surface_step',cfg.solver.surface_step_m, ...
        'bottom_step',cfg.solver.bottom_probe_step_m,'side_panels',cfg.solver.side_panels, ...
        'bottom_representation','image_neumann','direction_y',1);
    if diffraction,opt.direction_y=cfg.incident.direction_y;end
    result=struct('schema','CRESTU-2D-RESULT-1','version','0.3-research', ...
        'name',cfg.name,'input',cfg,'dofs',{cfg.dofs},'omega_rad_s',cfg.omega_rad_s, ...
        'reference_yz_m',cfg.reference_yz_m,'geometry',geo,'phase',cfg.phase, ...
        'radiation_normalization','unit velocity; roll unit angular velocity', ...
        'physical_model','finite_depth','water_depth_m',cfg.fluid.depth_m,'augmentation','none', ...
        'representation','direct_boundary_potential_and_normal_derivative_with_exact_bottom_image', ...
        'force_integration','constant body potential with straight-panel midpoint pressure integration', ...
        'finite_state_columns',{{'sway_unit_velocity','heave_unit_velocity','roll_unit_angular_velocity','diffraction_per_elevation_amplitude'}}, ...
        'capability','Finite-depth research option. Independent qualification is limited to saved Gate B cases; local body fields and zero frequency are not certified.');
    result.units=struct('A',{{'kg/m','kg/m','kg';'kg/m','kg/m','kg';'kg','kg','kg*m'}}, ...
        'B',{{'kg/(m*s)','kg/(m*s)','kg/s';'kg/(m*s)','kg/(m*s)','kg/s';'kg/s','kg/s','kg*m/s'}}, ...
        'F_exc',{{'N/m','N/m','N'}},'F_exc_per_amplitude',{{'N/m^2','N/m^2','N/m'}}, ...
        'note','Units tables use full sway/heave/roll order; all loads per unit longitudinal length.');
    result.normalization='A_hat=D^-1*A*D^-1/(rho*L^2); B_hat=D^-1*B*D^-1/(rho*omega*L^2); D=diag(1,1,L) selected DOFs';
    result.A=zeros(nd,nd,nf);result.B=result.A;result.A_hat=result.A;result.B_hat=result.A;result.B_energy=result.A;
    result.F_exc_per_amplitude=complex(zeros(nd,diffraction*nf));result.F_FK_per_amplitude=result.F_exc_per_amplitude;
    result.farfield_velocity_potential=complex(zeros(2,nd,nf));
    result.radiation_potential=complex(zeros(geo.n,nd,nf));
    result.source_strength=complex(zeros(0,nd+diffraction,nf));
    result.auxiliary_strength=complex(zeros(0,nd+diffraction,nf));
    result.force_points_yz_m=geo.mid;result.force_weights_m=geo.length;result.finite_state=cell(1,nf);
    for f=1:nf
        r=crestu2d.finite_boundary_solve(nodes,cfg.omega_rad_s(f),opt);result.finite_state{f}=r;
        result.A(:,:,f)=r.A(ids,ids);result.B(:,:,f)=r.B(ids,ids);
        result.A_hat(:,:,f)=r.A_hat(ids,ids);result.B_hat(:,:,f)=r.B_hat(ids,ids);result.B_energy(:,:,f)=r.B_energy(ids,ids);
        result.radiation_potential(:,:,f)=r.body_radiation_potential(:,ids);
        result.farfield_velocity_potential(:,:,f)=r.farfield_radiation_potential_global(:,ids);
        if diffraction
            result.F_exc_per_amplitude(:,f)=r.F(ids);result.F_FK_per_amplitude(:,f)=r.F_FK(ids);
            result.F_Haskind_per_amplitude(:,f)=r.F_Haskind(ids);
            % Same dimensionless incident/scattered convention as the deep adapter.
            result.diffraction_potential(:,f)=r.body_scattered_potential_per_amplitude*cfg.omega_rad_s(f)/g;
            result.body_scattered_potential_per_amplitude(:,f)=r.body_scattered_potential_per_amplitude;
        end
        result.diagnostics(f)=struct('omega_rad_s',r.omega,'k_m_inv',r.right_modes.k, ...
            'matrix_rcond',r.matrix_rcond,'linear_residual',r.equation_residual, ...
            'reciprocity_A',r.reciprocity_A,'reciprocity_B',r.reciprocity_B, ...
            'min_damping_eigenvalue_hat',min(eig((r.B_hat+r.B_hat.')/2)), ...
            'energy_relative',r.energy_relative,'haskind_relative',r.haskind_relative, ...
            'bottom_boundary_relative',r.bottom_probe.rms_scaled,'dispersion_relative',r.right_modes.dispersion_relative, ...
            'side_modal_basis_rcond',r.right_modes.basis_rcond,'boundary_review_required',true, ...
            'conditioning_review_required',r.matrix_rcond<1e-3);
    end
    result.F_exc=result.F_exc_per_amplitude;
    if diffraction,result.F_exc=result.F_exc*cfg.incident.amplitude_m;end
end
