function [freeSurface, bottom, outerBoundary, audit] = ...
    apply_rankine_outer_truncation(freeSurface, bottom, outerBoundary, ...
    cfg, wavelength)
% APPLY_RANKINE_OUTER_TRUNCATION Build an audit-only closed frustum domain.
% The absent/default q=1.5 path returns the legacy meshes without mutation.

    validateattributes(wavelength, {'numeric'}, ...
        {'scalar', 'real', 'positive', 'finite'});
    specification = default_specification();
    if isfield(cfg, 'outer_truncation')
        specification = cfg.outer_truncation;
    end
    legacyRadius = cfg.fs.r_outer;
    baselineQ = (legacyRadius - cfg.fs.r_inner) / wavelength;
    desiredTopRadius = max(legacyRadius, cfg.fs.r_inner + ...
        specification.topRadiusPerWavelength * wavelength);
    desiredBottomRadius = max(legacyRadius, cfg.fs.r_inner + ...
        specification.bottomRadiusPerWavelength * wavelength);
    beforeCounts = [freeSurface.n_panels, bottom.n_panels, ...
        outerBoundary.n_panels];
    tolerance = 64 * eps(max([legacyRadius, desiredTopRadius, ...
        desiredBottomRadius, 1]));
    extensionRequested = desiredTopRadius > legacyRadius + tolerance || ...
        desiredBottomRadius > legacyRadius + tolerance;
    thetaControls = resolve_theta_controls(cfg);
    thetaResolutionRequested = any([thetaControls.common, ...
        thetaControls.top, thetaControls.bottom] > 0);
    qualityControlledTransition = ...
        get_polar_topology_mode(cfg) == "QUALITY_CONTROLLED_V2";
    policy = policy_specification();

    if (~specification.enabled || ~extensionRequested) && ...
            ~thetaResolutionRequested
        audit = unchanged_audit(specification, policy, wavelength, ...
            legacyRadius, baselineQ, beforeCounts, freeSurface, bottom, ...
            outerBoundary);
        return
    end
    assert(cfg.n_bodies == 1 && cfg.isx == 0 && cfg.isy == 0, ...
        'CRESTU:OuterTruncationScope', ...
        'Active frustum instrumentation is limited to one full-domain body.');
    assert(cfg.water_depth > 0 && ~isempty(bottom) && ~isempty(outerBoundary), ...
        'CRESTU:OuterTruncationDepth', ...
        'Active frustum instrumentation requires a finite-depth closed domain.');

    topLegacyRing = extract_outer_ring(freeSurface, 0.0, legacyRadius);
    bottomLegacyRing = extract_outer_ring(bottom, -cfg.water_depth, legacyRadius);
    assert(size(topLegacyRing, 1) == size(bottomLegacyRing, 1), ...
        'CRESTU:OuterTruncationLegacyRing', ...
        'Legacy free-surface and bottom outer rings have different node counts.');
    legacyThetaCount = size(topLegacyRing, 1);
    topThetaTarget = max_ring_edge(topLegacyRing);
    bottomThetaTarget = max_ring_edge(bottomLegacyRing);
    topRadialTarget = outer_band_radial_target(freeSurface, legacyRadius);
    bottomRadialTarget = outer_band_radial_target(bottom, legacyRadius);
    wallTarget = cfg.water_depth / cfg.fs.nz_farfield;
    assert(isfinite(wallTarget) && wallTarget > 0, ...
        'CRESTU:OuterTruncationWallTarget', ...
        'The Fine-baseline wall target depth/Nz is invalid.');
    [topThetaSelection, bottomThetaSelection, thetaSelection] = ...
        choose_endpoint_theta_counts(desiredTopRadius, topThetaTarget, ...
        desiredBottomRadius, bottomThetaTarget, legacyRadius, ...
        legacyThetaCount, thetaControls);
    topThetaCount = topThetaSelection.chosenCount;
    bottomThetaCount = bottomThetaSelection.chosenCount;
    [commonThetaCount, commonThetaProvenance] = ...
        choose_common_wall_count(topThetaCount, bottomThetaCount, ...
        thetaControls);
    startAngle = atan2(topLegacyRing(1, 2), topLegacyRing(1, 1));

    [freeSurface, topRing, topInfo] = prepare_horizontal_surface( ...
        freeSurface, desiredTopRadius, legacyRadius, commonThetaCount, ...
        startAngle, 0.0, topRadialTarget, topThetaTarget, cfg, 2, ...
        thetaResolutionRequested, qualityControlledTransition);
    [bottom, bottomRing, bottomInfo] = prepare_horizontal_surface( ...
        bottom, desiredBottomRadius, legacyRadius, commonThetaCount, ...
        startAngle, -cfg.water_depth, bottomRadialTarget, ...
        bottomThetaTarget, cfg, 4, thetaResolutionRequested, ...
        qualityControlledTransition);
    topInfo.endpointThetaNodeCount = topThetaCount;
    topInfo.wallRingNodeCount = size(topRing, 1);
    topInfo.endpointToWallCountTransition = topThetaCount ~= commonThetaCount;
    topInfo.transitionBoundaryType = 2;
    bottomInfo.endpointThetaNodeCount = bottomThetaCount;
    bottomInfo.wallRingNodeCount = size(bottomRing, 1);
    bottomInfo.endpointToWallCountTransition = ...
        bottomThetaCount ~= commonThetaCount;
    bottomInfo.transitionBoundaryType = 4;
    [outerBoundary, wallInfo] = build_frustum_wall(topRing, bottomRing, ...
        desiredTopRadius, desiredBottomRadius, cfg.water_depth, wallTarget, ...
        topThetaTarget, bottomThetaTarget, cfg.isx, cfg.isy);

    topFingerprint = mesh_fingerprint(freeSurface);
    bottomFingerprint = mesh_fingerprint(bottom);
    outerFingerprint = mesh_fingerprint(outerBoundary);
    geometryDiagnostics = audit_axisymmetric_wall_geometry( ...
        outerBoundary, topRing, bottomRing, commonThetaCount, ...
        topThetaCount, bottomThetaCount, topInfo, bottomInfo, ...
        commonThetaProvenance);
    afterCounts = [freeSurface.n_panels, bottom.n_panels, ...
        outerBoundary.n_panels];
    actualTopTheta = max_ring_edge(topRing);
    actualBottomTheta = max_ring_edge(bottomRing);
    resolutionStatuses = {topInfo.radialResolution, ...
        topInfo.thetaResolution, bottomInfo.radialResolution, ...
        bottomInfo.thetaResolution, wallInfo.slantResolution, ...
        wallInfo.topTangentialResolution, ...
        wallInfo.bottomTangentialResolution};
    resolutionPass = all(cellfun(@(item) item.accepted, resolutionStatuses));
    resolutionHeld = all(cellfun(@(item) ...
        item.heldWithinTolerance, resolutionStatuses));
    roundingFinerException = any(cellfun(@(item) ...
        item.roundingFinerException, resolutionStatuses)) || ...
        topThetaSelection.roundingFinerException || ...
        bottomThetaSelection.roundingFinerException || ...
        wallInfo.countSelection.roundingFinerException;
    assert(resolutionPass, 'CRESTU:OuterTruncationResolution', ...
        'A derived frustum spacing is more than 5%% coarser than its target.');

    audit = struct('schemaVersion', 2, 'policy', policy, ...
        'polarTopologyMode', char(get_polar_topology_mode(cfg)), ...
        'enabled', true, 'inputMode', specification.inputMode, ...
        'geometryModified', true, ...
        'independentTopQ', specification.topRadiusPerWavelength, ...
        'independentBottomQ', specification.bottomRadiusPerWavelength, ...
        'wavelengthM', wavelength, 'legacyRadiusM', legacyRadius, ...
        'legacyRadiusPerWavelength', baselineQ, ...
        'effectiveTopRadiusM', desiredTopRadius, ...
        'effectiveBottomRadiusM', desiredBottomRadius, ...
        'effectiveTopRadiusPerWavelength', ...
            (desiredTopRadius - cfg.fs.r_inner) / wavelength, ...
        'effectiveBottomRadiusPerWavelength', ...
            (desiredBottomRadius - cfg.fs.r_inner) / wavelength, ...
        'legacyThetaNodeCount', legacyThetaCount, ...
        'commonOuterThetaNodeCount', commonThetaCount, ...
        'legacyThetaTargetM', max(topThetaTarget, bottomThetaTarget), ...
        'legacyTopThetaTargetM', topThetaTarget, ...
        'legacyBottomThetaTargetM', bottomThetaTarget, ...
        'legacyRadialTargetM', max(topRadialTarget, bottomRadialTarget), ...
        'legacyTopRadialTargetM', topRadialTarget, ...
        'legacyBottomRadialTargetM', bottomRadialTarget, ...
        'topTargetProvenance', ...
            'final-legacy-free-surface-outer-ring/band-vertices', ...
        'bottomTargetProvenance', ...
            'final-legacy-bottom-outer-ring/band-vertices-independent-of-FS', ...
        'legacyWallSlantTargetM', wallTarget, ...
        'thetaTargetPerWavelength', ...
            max(topThetaTarget, bottomThetaTarget) / wavelength, ...
        'topThetaTargetPerWavelength', topThetaTarget / wavelength, ...
        'bottomThetaTargetPerWavelength', bottomThetaTarget / wavelength, ...
        'radialTargetPerWavelength', ...
            max(topRadialTarget, bottomRadialTarget) / wavelength, ...
        'topRadialTargetPerWavelength', topRadialTarget / wavelength, ...
        'bottomRadialTargetPerWavelength', bottomRadialTarget / wavelength, ...
        'wallSlantTargetPerWavelength', wallTarget / wavelength, ...
        'actualMaximumThetaPerWavelength', ...
            max(actualTopTheta, actualBottomTheta) / wavelength, ...
        'actualTopThetaPerWavelength', actualTopTheta / wavelength, ...
        'actualBottomThetaPerWavelength', actualBottomTheta / wavelength, ...
        'actualTopMaximumRadialPerWavelength', ...
            topInfo.maximumRadialStep / wavelength, ...
        'actualBottomMaximumRadialPerWavelength', ...
            bottomInfo.maximumRadialStep / wavelength, ...
        'actualWallMaximumSlantPerWavelength', ...
            wallInfo.maximumSlantStep / wavelength, ...
        'roundingPolicy', ['Ntheta=nearest-multiple-4-if-within-5pct-', ...
            'else-4*ceil;Nz=round-if-within-5pct-else-ceil;', ...
            'finer-exceptions-are-not-held'], ...
        'configuredThetaControls', thetaControls, ...
        'topOuterThetaNodeCount', topThetaCount, ...
        'bottomOuterThetaNodeCount', bottomThetaCount, ...
        'commonWallCountProvenance', commonThetaProvenance, ...
        'topWallRingNodeCount', size(topRing, 1), ...
        'bottomWallRingNodeCount', size(bottomRing, 1), ...
        'thetaCountSelection', thetaSelection, ...
        'topThetaCountSelection', topThetaSelection, ...
        'bottomThetaCountSelection', bottomThetaSelection, ...
        'resolutionPass', resolutionPass, ...
        'resolutionHeld', resolutionHeld, ...
        'roundingFinerException', roundingFinerException, ...
        'componentPanelCountsBefore', beforeCounts, ...
        'componentPanelCountsAfter', afterCounts, ...
        'topSurfaceDerived', topInfo, 'bottomSurfaceDerived', bottomInfo, ...
        'wallDerived', wallInfo, ...
        'geometryDiagnostics', geometryDiagnostics, ...
        'freeSurfaceHash', topFingerprint.hash, ...
        'bottomHash', bottomFingerprint.hash, ...
        'outerBoundaryHash', outerFingerprint.hash, ...
        'connectorComponent', 'outer_boundary/FARFIELD', ...
        'sensitivityLabel', 'top/bottom-truncation-shape-sensitivity', ...
        'derivedClosureWhitelist', {{'surface-annulus-panel-count', ...
            'surface-outer-ring-node-count', 'endpoint-theta-count', ...
            'wall-ring-count-transition', 'wall-z-level-count', ...
            'wall-panel-count', 'vertices', 'centers', 'normals', ...
            'areas', 'component-hashes', 'merged-hash', 'matrix-size'}});
end

function specification = default_specification()
    specification = struct('enabled', false, ...
        'topRadiusPerWavelength', 1.5, ...
        'bottomRadiusPerWavelength', 1.5, ...
        'inputMode', 'legacy-absent', ...
        'minimumRadiusPerWavelength', 1.5);
end

function controls = resolve_theta_controls(cfg)
% RESOLVE_THETA_CONTROLS Read optional P-full endpoint controls.
% A zero value is an unset sentinel.  In particular, a q-only scientific
% truncation case does not acquire a second configured input: the changed
% endpoint count is derived internally from its frozen legacy spacing.
    controls = struct('common', 0, 'top', 0, 'bottom', 0, ...
        'commonField', 'outerThetaPanelCount', ...
        'topField', 'freeSurfaceOuterThetaPanelCount', ...
        'bottomField', 'bottomOuterThetaPanelCount');
    if ~isfield(cfg, 'phase2_2_controls')
        return
    end
    source = cfg.phase2_2_controls;
    controls.common = optional_theta_value(source, ...
        controls.commonField);
    controls.top = optional_theta_value(source, controls.topField);
    controls.bottom = optional_theta_value(source, controls.bottomField);
end

function value = optional_theta_value(source, name)
    value = 0;
    if isfield(source, name)
        value = source.(name);
    end
    assert(isnumeric(value) && isscalar(value) && isfinite(value) && ...
        value >= 0 && fix(value) == value && ...
        (value == 0 || mod(value, 4) == 0), ...
        'CRESTU:OuterTruncationThetaControl', ...
        '%s must be zero (unset) or a positive multiple of four.', name);
end

