function hashText = canonical_lf_file_hash(filename)
    fileID = fopen(filename, 'rb');
    assert(fileID >= 0, 'CRESTU:Phase32CanonicalHashOpen', ...
        'Cannot open file for hashing: %s', filename);
    cleanup = onCleanup(@() fclose(fileID));
    bytes = fread(fileID, Inf, '*uint8')';
    clear cleanup
    textValue = native2unicode(bytes, 'UTF-8');
    textValue = strrep(textValue, [char(13), newline], newline);
    textValue = strrep(textValue, char(13), newline);
    hashText = sha256_hash(uint8(unicode2native(textValue, 'UTF-8')));
end

function [blobID, tracked] = git_blob_id(repositoryRoot, relativePath)
    relativeForward = strrep(char(relativePath), '\', '/');
    [output, status] = run_git(repositoryRoot, ...
        sprintf('rev-parse "HEAD:%s"', relativeForward));
    tracked = status == 0 && strlength(strtrim(string(output))) == 40;
    if tracked
        blobID = strtrim(string(output));
    else
        blobID = "";
    end
end

function [output, status] = run_git(repositoryRoot, arguments)
    [status, output] = system(sprintf('git -C "%s" %s', ...
        repositoryRoot, arguments));
end

function value = same_path(firstPath, secondPath)
    value = strcmpi(normalize_path(firstPath), normalize_path(secondPath));
end

function value = path_is_within(candidatePath, rootPath)
    candidate = normalize_path(candidatePath);
    root = normalize_path(rootPath);
    value = strcmpi(candidate, root) || startsWith(lower(candidate), ...
        [lower(root), filesep]);
end

function value = normalize_path(inputPath)
    value = strrep(char(string(inputPath)), '/', filesep);
    while numel(value) > 3 && endsWith(value, filesep)
        value(end) = [];
    end
end

function text = yes_no(value)
    if value
        text = 'YES';
    else
        text = 'NO';
    end
end
