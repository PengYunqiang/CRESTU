function summary = Finalize_Phase3_2_Blocked_Evidence()
% FINALIZE_PHASE3_2_BLOCKED_EVIDENCE Close Phase 3.2 honestly at mesh gate.

    %% Stage 1: Re-read authoritative v1-v4 evidence

    definition = phase32.definition();
    phase32.initialize(definition);
    artifactDirectory = definition.artifactDirectory;
    manifest = readtable(fullfile(artifactDirectory, ...
        'Phase3_2_Mesh_Manifest.csv'), 'TextType', 'string');
    quality = readtable(fullfile(artifactDirectory, ...
        'Phase3_2_Mesh_Quality.csv'), 'TextType', 'string');
    isolation = readtable(fullfile(artifactDirectory, ...
        'Phase3_2_Mesh_Control_Isolation.csv'), 'TextType', 'string');
    legacyRegression = readtable(fullfile(artifactDirectory, ...
        'Phase3_2_Legacy_Mesh_Regression.csv'), 'TextType', 'string');
    assert(height(manifest) == 18 && height(quality) == 72, ...
        'CRESTU:Phase32FinalMeshEvidenceShape', ...
        'Final v4 mesh evidence has an unexpected row count.');
    assert(all(legacyRegression.exact_hash_regression) && ...
        any(manifest.geometry_gate_status == "FAIL") && ...
        any(isolation.geometry_control_isolation == "FAIL"), ...
        'CRESTU:Phase32FinalBlockedPremise', ...
        'The blocked finalizer requires exact legacy PASS and v4 mesh FAIL.');

    qualityCounts = recompute_quality_counts(quality);
    gateSummary = split_gate_semantics(quality, isolation, legacyRegression);
    writetable(struct2table(qualityCounts), fullfile(artifactDirectory, ...
        'Phase3_2_Final_Report_Integrity.csv'));

    %% Stage 2: Emit explicit NOT-RUN numerical tables

    sentinel = blocked_convergence_table('sentinel', 18, 0, ...
        'MESH_GEOMETRY_GATE_FAIL_BEFORE_BEM');
    formal = blocked_convergence_table('formal', 48, 0, ...
        'SENTINEL_NOT_AUTHORIZED_BY_GEOMETRY_GATE');
    condition = table("all", "NOT_RUN_BLOCKED", NaN, NaN, NaN, NaN, ...
        "No Rankine matrix assembled after geometry fail-early", ...
        'VariableNames', {'scope', 'solve_status', 'raw_rcond', ...
        'scaled_rcond', 'maximum_linear_residual', ...
        'maximum_algebraic_residual', 'reason'});
    resonance = table("1.30:0.02:1.50", "NOT_RUN_BLOCKED", NaN, NaN, ...
        NaN, NaN, "MESH_GEOMETRY_GATE_FAIL", ...
        'VariableNames', {'frequency_grid_rad_s', 'status', ...
        'peak_frequency_rad_s', 'peak_RAO3_m_per_m', ...
        'D3_minimum_frequency_rad_s', 'minimum_abs_D3_N_per_m', 'reason'});
    writetable(sentinel, fullfile(artifactDirectory, ...
        'Phase3_2_Sentinel_Convergence.csv'));
    writetable(formal, fullfile(artifactDirectory, ...
        'Phase3_2_Formal_Convergence.csv'));
    writetable(condition, fullfile(artifactDirectory, ...
        'Phase3_2_Condition_Residual.csv'));
    writetable(resonance, fullfile(artifactDirectory, ...
        'Phase3_2_Resonance_Tracking.csv'));

    %% Stage 3: Final status and reviewer checklist

    finalStatus = build_final_status(gateSummary, qualityCounts);
    writetable(finalStatus, fullfile(artifactDirectory, ...
        'Phase3_2_Final_Status.csv'));
    reviewer = build_reviewer_gate(gateSummary, qualityCounts);
    writetable(reviewer, fullfile(artifactDirectory, ...
        'Phase3_2_Reviewer_Gate.csv'));
    write_main_report(definition, manifest, quality, gateSummary, ...
        qualityCounts);
    write_human_review(definition, manifest, quality);
    write_independent_review(definition, reviewer);
    write_production_diff(definition);
    write_git_audits(definition);

    summary = struct('schemaVersion', 1, 'overallStatus', 'BLOCKED', ...
        'meshFamilyVersion', 'v4', 'meshOnlyCaseCount', height(manifest), ...
        'bemCaseCount', 0, 'legacyQOnlyExactRegression', true, ...
        'meshGeometryGate', char(gateSummary.MESH_QUALITY_GATE), ...
        'componentQualityRowsTotal', qualityCounts.COMPONENT_QUALITY_ROWS_TOTAL, ...
        'componentQualityRowsPass', qualityCounts.COMPONENT_QUALITY_ROWS_PASS, ...
        'componentQualityRowsFail', qualityCounts.COMPONENT_QUALITY_ROWS_FAIL, ...
        'reviewerBlockers', 1, ...
        'readyForProduction', false, ...
        'readyForQuantitativeWamitAudit', false);
    fprintf('[RESULT] PHASE3_2_OVERALL = BLOCKED\n');
    fprintf('[RESULT] MESH_GEOMETRY_GATE = FAIL\n');
    fprintf('[RESULT] REVIEWER_BLOCKERS = 1\n');
    fprintf('[RESULT] READY_FOR_PRODUCTION = NO\n');
end

function counts = recompute_quality_counts(quality)
% RECOMPUTE_QUALITY_COUNTS Derive report counts directly from raw quality CSV.

    statuses = string(quality.component_gate_status);
    counts = struct( ...
        'COMPONENT_QUALITY_ROWS_TOTAL', height(quality), ...
        'COMPONENT_QUALITY_ROWS_PASS', nnz(statuses == "PASS"), ...
        'COMPONENT_QUALITY_ROWS_FAIL', nnz(statuses == "FAIL"));
    assert(counts.COMPONENT_QUALITY_ROWS_PASS + ...
        counts.COMPONENT_QUALITY_ROWS_FAIL == ...
        counts.COMPONENT_QUALITY_ROWS_TOTAL, ...
        'CRESTU:Phase32QualityStatusCoverage', ...
        'Quality CSV contains a status other than PASS/FAIL.');
end

function gates = split_gate_semantics(quality, isolation, legacyRegression)
% SPLIT_GATE_SEMANTICS Keep activation/isolation/refinement/quality distinct.

    regionActivation = all(isolation.body_count_changes) && ...
        all(isolation.free_surface_count_changes) && ...
        all(isolation.bottom_count_changes) && ...
        all(isolation.farfield_count_changes);
    outerIsolation = all(isolation.outer_extent_fixed) && ...
        all(isolation.physics_hash_fixed) && ...
        all(isolation.source_hash_fixed);
    legacyRegressionPass = all(legacyRegression.exact_hash_regression);
    monotonicFamily = all(isolation.body_h_strictly_decreases) && ...
        all(isolation.free_surface_h_strictly_decreases) && ...
        all(isolation.bottom_h_strictly_decreases) && ...
        all(isolation.wall_h_strictly_decreases) && ...
        all(isolation.transition_h_strictly_decreases);
    qualityPass = all(string(quality.component_gate_status) == "PASS");
    controlIsolation = regionActivation && outerIsolation && ...
        legacyRegressionPass && monotonicFamily;
    gates = struct( ...
        'REGION_CONTROL_ACTIVATION', pass_fail(regionActivation), ...
        'OUTER_EXTENT_ISOLATION', pass_fail(outerIsolation), ...
        'LEGACY_Q_ONLY_REGRESSION', pass_fail(legacyRegressionPass), ...
        'MONOTONIC_REFINEMENT_FAMILY', pass_fail(monotonicFamily), ...
        'MESH_QUALITY_GATE', pass_fail(qualityPass), ...
        'MESH_CONTROL_ISOLATION', pass_fail(controlIsolation));
end

