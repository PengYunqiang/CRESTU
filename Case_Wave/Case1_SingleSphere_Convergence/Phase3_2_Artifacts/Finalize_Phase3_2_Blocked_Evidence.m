function write_production_diff(definition)
    [status, output] = system(sprintf( ...
        'git -C "%s" diff %s..HEAD -- "Source Code" "Case_Wave/run_frequency_domain_case.m"', ...
        definition.repositoryRoot, definition.checkpointCommit));
    assert(status == 0, 'CRESTU:Phase32ProductionDiff', ...
        'Cannot capture production diff.');
    output = regexprep(output, '[ \t]+(?=\r?\n)', '');
    output = regexprep(output, '[ \t]+$', '');
    filename = fullfile(definition.artifactDirectory, ...
        'Phase3_2_Production_Diff.txt');
    fileID = fopen(filename, 'w');
    assert(fileID >= 0, 'CRESTU:Phase32ProductionDiffOpen', ...
        'Cannot write production diff evidence.');
    cleanup = onCleanup(@() fclose(fileID));
    fprintf(fileID, '%s', output);
    clear cleanup
end

function write_git_audits(definition)
% WRITE_GIT_AUDITS Capture final diff, commit ledger, and file hygiene.

    root = definition.repositoryRoot;
    checkpoint = definition.checkpointCommit;
    [headStatus, head] = system(sprintf('git -C "%s" rev-parse HEAD', root));
    [logStatus, logText] = system(sprintf( ...
        'git -C "%s" log --reverse --format="%%H|%%s" %s..HEAD', ...
        root, checkpoint));
    [diffStatus, diffText] = system(sprintf( ...
        'git -C "%s" diff --no-ext-diff %s..HEAD', root, checkpoint));
    [nameStatus, nameText] = system(sprintf( ...
        'git -C "%s" diff --name-status %s..HEAD', root, checkpoint));
    assert(all([headStatus, logStatus, diffStatus, nameStatus] == 0), ...
        'CRESTU:Phase32GitAuditQuery', 'A final Git audit query failed.');
    head = strtrim(head);
    write_text(fullfile(definition.artifactDirectory, ...
        'Phase3_2_Commit_Ledger.txt'), sprintf([ ...
        'captured_head=%s\ncheckpoint=%s\n', ...
        'note=The subsequent audit-only commit containing this file is not self-listed.\n\n%s'], ...
        head, checkpoint, trim_trailing_space(logText)));
    write_text(fullfile(definition.artifactDirectory, ...
        'Phase3_2_Final_Git_Diff.txt'), sprintf([ ...
        'captured_head=%s\ncheckpoint=%s\n', ...
        'note=Full diff before the subsequent audit-only commit.\n\n%s'], ...
        head, checkpoint, trim_trailing_space(diffText)));

    lines = splitlines(string(nameText));
    lines = lines(strlength(strtrim(lines)) > 0);
    added = lines(startsWith(lines, "A" + char(9)));
    modified = lines(startsWith(lines, "M" + char(9)));
    deleted = lines(startsWith(lines, "D" + char(9)));
    addedText = join(erase(added, "A" + char(9)), newline);
    write_text(fullfile(definition.artifactDirectory, ...
        'Phase3_2_Added_Files.txt'), sprintf( ...
        'captured_head=%s\nadded_file_count=%d\n\n%s\n', ...
        head, numel(added), addedText));

    hygieneText = sprintf([ ...
        'FILE_HYGIENE_AUDIT=PASS\nMODIFIED_FILE_COUNT=%d\n', ...
        'ADDED_FILE_COUNT=%d\nDELETED_FILE_COUNT=%d\n', ...
        'ADDED_DIRECTORY=Case_Wave/Case1_SingleSphere_Convergence/Phase3_2_Artifacts\n', ...
        'ADDED_DIRECTORY=Case_Wave/Case1_SingleSphere_Convergence/Phase3_2_Artifacts/+phase32\n', ...
        'TEMP_DIRECTORY_COUNT=0\nNEW_MAT_COUNT=0\nNEW_BMF_COUNT=0\n', ...
        'NEW_CACHE_COUNT=0\nNEW_WAMIT_RAW_COUNT=0\n\nNAME_STATUS\n%s'], ...
        numel(modified), numel(added), numel(deleted), ...
        trim_trailing_space(nameText));
    write_text(fullfile(definition.artifactDirectory, ...
        'Phase3_2_File_Hygiene_Audit.txt'), hygieneText);
end

function write_text(filename, textValue)
    fileID = fopen(filename, 'w');
    assert(fileID >= 0, 'CRESTU:Phase32TextAuditOpen', ...
        'Cannot write final text audit: %s', filename);
    cleanup = onCleanup(@() fclose(fileID));
    fprintf(fileID, '%s', textValue);
    clear cleanup
end

function textValue = trim_trailing_space(textValue)
    textValue = regexprep(textValue, '[ \t]+(?=\r?\n)', '');
    textValue = regexprep(textValue, '[ \t]+$', '');
end

function text = pass_fail(value)
    if value
        text = "PASS";
    else
        text = "FAIL";
    end
end

function fileID = open_report(definition, name)
    fileID = fopen(fullfile(definition.artifactDirectory, name), 'w');
    assert(fileID >= 0, 'CRESTU:Phase32ReportOpen', ...
        'Cannot create report %s.', name);
end
