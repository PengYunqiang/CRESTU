function summary = Finalize_Phase3_2B()
% FINALIZE_PHASE3_2B Close blocked continuation without invented results.

    %% Stage 1: Re-read and enforce all completed evidence

    definition = phase32b.initialize();
    artifact = definition.artifactDirectory;
    frozen = readtable(fullfile(artifact, ...
        'Phase3_2B_V5_Frozen_Mesh_Manifest.csv'), 'TextType', 'string');
    response = readtable(fullfile(artifact, ...
        'Phase3_2B_Sentinel_Response.csv'), 'TextType', 'string');
    convergence = readtable(fullfile(artifact, ...
        'Phase3_2B_Sentinel_Convergence.csv'), 'TextType', 'string');
    legacy = readtable(fullfile(artifact, ...
        'Phase3_2B_Legacy_Regression.csv'), 'TextType', 'string');
    reviewerFile = fullfile(artifact, 'Phase3_2B_Reviewer_Gate.csv');
    assert(isfile(reviewerFile), 'CRESTU:Phase32BReviewerMissing', ...
        'Independent reviewer gate must exist before finalization.');
    reviewer = readtable(reviewerFile, 'TextType', 'string', ...
        'Delimiter', ',');
    assert(height(frozen) == 18 && ...
        all(frozen.baseline_reproducibility == "PASS"), ...
        'CRESTU:Phase32BFinalFrozen', 'Frozen v5 evidence is incomplete.');
    assert(height(response) == 18 && ...
        numel(unique(response.case_id)) == 18 && ...
        all(response.preassembly_status == "PASS") && ...
        all(response.algebraic_gate_status == "PASS") && ...
        all(lower(response.cache_status) == "miss"), ...
        'CRESTU:Phase32BFinalSentinel', ...
        'Sentinel clean/algebraic evidence is incomplete.');
    assert(height(legacy) == 16 && all(legacy.status == "PASS") && ...
        nnz(legacy.suite_position == "START") == 8 && ...
        nnz(legacy.suite_position == "END") == 8, ...
        'CRESTU:Phase32BFinalLegacy', ...
        'Start/end legacy/control regression must be 16/16 PASS.');
    mandatory = convergence.gate_role == "MANDATORY";
    mandatoryFailCount = nnz(convergence.gate_status(mandatory) == "FAIL");
    assert(nnz(mandatory) == 24 && mandatoryFailCount == 16, ...
        'CRESTU:Phase32BFinalResponseGate', ...
        'Sentinel response FAIL count no longer matches authoritative evidence.');
    reviewerBlockers = sum(reviewer.blocker_count);

    %% Stage 2: Persist explicit not-run records for blocked continuations

    write_not_run_tables(definition);
    finalStatus = build_final_status(reviewerBlockers);
    writetable(finalStatus, fullfile(artifact, ...
        'Phase3_2B_Final_Status.csv'));
    write_main_report(definition, response, convergence, reviewerBlockers);
    write_human_review(definition);

    %% Stage 3: Write Git, commit, and file-hygiene audits

    write_commit_ledger(definition);
    write_git_diff(definition);
    write_file_hygiene(definition);
    summary = struct('schemaVersion', 1, 'overallStatus', 'FAIL', ...
        'v5MeshReproducibility', 'PASS', ...
        'sentinelAlgebraicGate', 'PASS', ...
        'sentinelResponseGate', 'FAIL', ...
        'mandatoryFailCount', mandatoryFailCount, ...
        'resonanceConvergence', 'NOT_RUN_BLOCKED', ...
        'formalMeshConvergence', 'NOT_RUN_BLOCKED', ...
        'reviewerBlockers', reviewerBlockers, ...
        'readyForPhase33WamitAttribution', false, ...
        'readyForProduction', false);
    fprintf('[RESULT] PHASE3_2B_OVERALL = FAIL\n');
    fprintf('[RESULT] SENTINEL_ALGEBRAIC_GATE = PASS\n');
    fprintf('[RESULT] SENTINEL_RESPONSE_GATE = FAIL\n');
    fprintf('[RESULT] RESONANCE_CONVERGENCE = NOT_RUN_BLOCKED\n');
    fprintf('[RESULT] FORMAL_MESH_CONVERGENCE = NOT_RUN_BLOCKED\n');
    fprintf('[RESULT] REVIEWER_BLOCKERS = %d\n', reviewerBlockers);
    fprintf('[RESULT] READY_FOR_PHASE3_3_WAMIT_ATTRIBUTION = NO\n');
    fprintf('[RESULT] READY_FOR_PRODUCTION = NO\n');
end

function write_not_run_tables(definition)
    stage = "RESONANCE_TRACKING";
    status = "NOT_RUN_BLOCKED";
    reason = "SENTINEL_RESPONSE_GATE_FAIL_16_OF_24_MANDATORY";
    plannedScope = "L1_L2_L3_AT_1P30_TO_1P50_STEP_0P02_RAD_PER_S";
    numericResultsPresent = "NO";
    writetable(table(stage, status, reason, plannedScope, ...
        numericResultsPresent), fullfile(definition.artifactDirectory, ...
        'Phase3_2B_Resonance_Tracking.csv'));

    stage = "FORMAL_RESPONSE";
    plannedScope = "L1_L2_L3_AT_0P5_TO_2P0_STEP_0P1_RAD_PER_S";
    writetable(table(stage, status, reason, plannedScope, ...
        numericResultsPresent), fullfile(definition.artifactDirectory, ...
        'Phase3_2B_Formal_Response.csv'));
    stage = "FORMAL_CONVERGENCE";
    writetable(table(stage, status, reason, plannedScope, ...
        numericResultsPresent), fullfile(definition.artifactDirectory, ...
        'Phase3_2B_Formal_Convergence.csv'));
end

