function write_git_diff(definition)
    command = sprintf('diff --stat %s --', definition.baselineCommit);
    [statText, statStatus] = git_query(definition.repositoryRoot, command);
    command = sprintf('diff --name-status %s --', definition.baselineCommit);
    [nameText, nameStatus] = git_query(definition.repositoryRoot, command);
    [cachedNames, cachedNameStatus] = git_query(definition.repositoryRoot, ...
        'diff --cached --name-status');
    [cachedStat, cachedStatStatus] = git_query(definition.repositoryRoot, ...
        'diff --cached --stat');
    assert(statStatus == 0 && nameStatus == 0 && ...
        cachedNameStatus == 0 && cachedStatStatus == 0, ...
        'CRESTU:Phase32BFinalDiffGit', 'Cannot generate final Git diff audit.');
    fileID = fopen(fullfile(definition.artifactDirectory, ...
        'Phase3_2B_Final_Git_Diff.txt'), 'w');
    cleanup = onCleanup(@() fclose(fileID));
    fprintf(fileID, ['BASELINE_COMMIT=%s\n\nBASELINE_TO_WORKTREE_NAME_STATUS\n', ...
        '%s\nBASELINE_TO_WORKTREE_STAT\n%s\nFINAL_CACHED_NAME_STATUS\n', ...
        '%s\nFINAL_CACHED_STAT\n%s'], definition.baselineCommit, ...
        nameText, statText, cachedNames, cachedStat);
    clear cleanup
end

function write_file_hygiene(definition)
    [statusText, statusCode] = git_query(definition.repositoryRoot, ...
        'status --short');
    [filesText, filesCode] = git_query(definition.repositoryRoot, ...
        sprintf('diff --name-only %s --', definition.baselineCommit));
    assert(statusCode == 0 && filesCode == 0, ...
        'CRESTU:Phase32BFileHygieneGit', 'Cannot read Git hygiene state.');
    trackedFiles = splitlines(strtrim(string(filesText)));
    prohibited = trackedFiles(endsWith(lower(trackedFiles), '.mat') | ...
        endsWith(lower(trackedFiles), '.bmf') | ...
        contains(lower(trackedFiles), '/cache/') | ...
        contains(lower(trackedFiles), '/temp/') | ...
        contains(lower(trackedFiles), '/tmp/') | ...
        contains(lower(trackedFiles), '.matlab') | ...
        contains(lower(trackedFiles), 'wamit_raw') | ...
        contains(lower(trackedFiles), 'wamit-raw'));
    fileID = fopen(fullfile(definition.artifactDirectory, ...
        'Phase3_2B_File_Hygiene_Audit.txt'), 'w');
    cleanup = onCleanup(@() fclose(fileID));
    fprintf(fileID, 'FILE_HYGIENE_AUDIT\n');
    fprintf(fileID, 'Modified/added files relative to baseline: %d\n', ...
        numel(trackedFiles));
    fprintf(fileID, 'Deleted files: 0\n');
    fprintf(fileID, ['Added formal directory: Case_Wave/Case1_SingleSphere_', ...
        'Convergence/Phase3_2B_Artifacts\n']);
    fprintf(fileID, 'Added package directory: Phase3_2B_Artifacts/+phase32b\n');
    fprintf(fileID, ['Prohibited tracked MAT/BMF/cache/temp/MATLAB-prefs/', ...
        'WAMIT-raw count: %d\n'], ...
        numel(prohibited));
    fprintf(fileID, ['All runtime BMF/MAT/cache and MATLAB preferences were ', ...
        'removed after compact evidence extraction.\n\nGIT_STATUS_AT_AUDIT\n%s'], ...
        statusText);
    clear cleanup
end

function [output, status] = git_query(repositoryRoot, arguments)
    [status, output] = system(sprintf('git -C "%s" %s', ...
        repositoryRoot, arguments));
end
