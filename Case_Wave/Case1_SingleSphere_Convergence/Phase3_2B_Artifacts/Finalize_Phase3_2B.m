        'PHASE3_2B_RESPONSE_CONVERGENCE_CN.md'), 'w');
    assert(fileID >= 0, 'CRESTU:Phase32BFinalReportOpen', ...
        'Cannot create final response convergence report.');
    cleanup = onCleanup(@() fclose(fileID));
    mandatory = convergence.gate_role == "MANDATORY";
    fprintf(fileID, '# CRESTU-1F Phase 3.2B 响应收敛最终报告\n\n');
    fprintf(fileID, '```ini\nPHASE3_2B_OVERALL = FAIL\n');
    fprintf(fileID, 'V5_MESH_REPRODUCIBILITY = PASS_18_OF_18\n');
    fprintf(fileID, 'SENTINEL_CLEAN_SOLVES = PASS_%d_OF_18_CACHE_MISS\n', ...
        nnz(lower(response.cache_status) == "miss"));
    fprintf(fileID, 'SENTINEL_ALGEBRAIC_GATE = PASS_%d_OF_18\n', ...
        nnz(response.algebraic_gate_status == "PASS"));
    fprintf(fileID, 'SENTINEL_RESPONSE_GATE = FAIL_%d_OF_%d_MANDATORY\n', ...
        nnz(convergence.gate_status(mandatory) == "FAIL"), nnz(mandatory));
    fprintf(fileID, 'RESONANCE_CONVERGENCE = NOT_RUN_BLOCKED\n');
    fprintf(fileID, 'FORMAL_MESH_CONVERGENCE = NOT_RUN_BLOCKED\n');
    fprintf(fileID, 'ASYMPTOTIC_RANGE = NOT_DEMONSTRATED_OVERALL\n');
    fprintf(fileID, 'PRODUCTION_MESH_CANDIDATE = NONE\n');
    fprintf(fileID, 'PHYSICAL_VALIDATION = PARTIAL\n');
    fprintf(fileID, 'REVIEWER_BLOCKERS = %d\n', reviewerBlockers);
    fprintf(fileID, 'READY_FOR_PHASE3_3_WAMIT_ATTRIBUTION = NO\n');
    fprintf(fileID, 'READY_FOR_PRODUCTION = NO\n```\n\n');
    fprintf(fileID, '## 已证明\n\n');
    fprintf(fileID, ['v5 网格 18/18 重生成、组件/组合网格和 source/control/operator ', ...
        'hash 全部匹配；18 个 sentinel 全为唯一临时目录中的 clean solve 和 ', ...
        'cache MISS。所有 raw/scaled rcond、radiation/diffraction residual、', ...
        'outer operator audit 和 finite gate 均通过。\n\n']);
    fprintf(fileID, '## 响应结论\n\n');
    fprintf(fileID, ['24 个 mandatory L2→L3 比较中 16 个超过预声明门槛。', ...
