function summary = Run_Phase3_2A_Generator_Audit()
% RUN_PHASE3_2A_GENERATOR_AUDIT Locate fail-before panels and producer chain.

    %% Stage 1: Freeze the read-only call-chain interpretation

    definition = phase32a.initialize();
    callChain = build_call_chain();
    writetable(callChain, fullfile(definition.artifactDirectory, ...
        'Phase3_2A_Generator_Call_Chain.csv'));

    %% Stage 2: Rebuild only low/high endpoint v4 meshes

    v4 = phase32.definition();
    frequencies = [0.5, 2.0]; % [rad/s]
    levels = v4.levels;
    diagnosticRows = repmat(empty_panel_record(), 0, 1);
    transitionRows = repmat(empty_transition_record(), 0, 1);
    diagnosticFile = fullfile(definition.artifactDirectory, ...
        'Phase3_2A_FailBefore_Panel_Diagnostics.csv');
    transitionFile = fullfile(definition.artifactDirectory, ...
        'Phase3_2A_Transition_H_Diagnostics.csv');

    caseCount = numel(frequencies) * numel(levels);
    completed = 0;
    for frequencyIndex = 1:numel(frequencies)
        omega = frequencies(frequencyIndex); % [rad/s]
        for levelIndex = 1:numel(levels)
            level = levels(levelIndex);
            completed = completed + 1;
            fprintf('[INFO] Generator audit %d/%d | %s | %.6g rad/s\n', ...
                completed, caseCount, level.name, omega);
            specification = phase32.create_case(v4, level, omega, ...
                'phase3_2a_generator_audit');
            cleanup = onCleanup(@() phase32.remove_runtime( ...
                v4, specification.runtimeDirectory));
            domain = build_bmf_domain(specification.configFile);
            assert_runtime_scope(definition, specification, domain);
            truncation = domain.cfg.outer_truncation.effective;
            waterlineCount = domain.outer_waterlines{1}.n_pts;
            components = {domain.body_list{1}, domain.fs, ...
                domain.seabed, domain.farfield};
            names = ["body"; "free_surface"; "bottom"; "farfield"];
            for componentIndex = 1:numel(components)
                mesh = components{componentIndex};
                [~, details] = phase32a.evaluate_component_quality( ...
                    mesh, names(componentIndex), definition);
                [~, aspectOrder] = sort(details.aspect_ratio, 'descend');
                [~, angleOrder] = sort(details.minimum_angle_deg, 'ascend');
                selectionCount = min(5, mesh.n_panels);
                for rankIndex = 1:selectionCount
                    panelIndex = aspectOrder(rankIndex);
                    diagnosticRows(end + 1, 1) = panel_record( ...
                        definition, specification, truncation, ...
                        names(componentIndex), mesh, details, panelIndex, ...
                        "WORST_ASPECT_RATIO", rankIndex, waterlineCount); %#ok<AGROW>
                    panelIndex = angleOrder(rankIndex);
                    diagnosticRows(end + 1, 1) = panel_record( ...
                        definition, specification, truncation, ...
                        names(componentIndex), mesh, details, panelIndex, ...
                        "WORST_MINIMUM_ANGLE", rankIndex, waterlineCount); %#ok<AGROW>
                end
            end
            transitionRows = append_transition_records(transitionRows, ...
                specification, domain, truncation);
            writetable(struct2table(diagnosticRows), diagnosticFile);
            writetable(struct2table(transitionRows), transitionFile);
            clear cleanup
        end
    end

    %% Stage 3: Classify evidence without overclaiming a unique root cause

    diagnostics = struct2table(diagnosticRows);
    transitions = struct2table(transitionRows);
    fsLow = diagnostics.component == "free_surface" & ...
        diagnostics.omega_rad_s == 0.5;
    bottomHigh = diagnostics.component == "bottom" & ...
        diagnostics.omega_rad_s == 2.0;
    fsWorstAspect = max(diagnostics.aspect_ratio(fsLow));
    bottomMinimumAngle = min(diagnostics.minimum_angle_deg(bottomHigh));
    bottomWorst = diagnostics(bottomHigh & ...
        diagnostics.minimum_angle_deg == bottomMinimumAngle, :);
    bottomSingleCenterFan = any(bottomWorst.generator_region == ...
        "BOTTOM_SINGLE_CENTER_FAN");
    summary = struct('schemaVersion', 1, ...
        'selectedCaseCount', caseCount, ...
        'diagnosticPanelRowCount', height(diagnostics), ...
        'transitionSummaryRowCount', height(transitions), ...
        'fsOmega0p5MaximumAspectRatio', fsWorstAspect, ...
        'bottomOmega2MinimumAngleDeg', bottomMinimumAngle, ...
        'bottomMinimumAngleFromSingleCenterFan', bottomSingleCenterFan, ...
        'metricBug', false, ...
        'classification', 'PRIMARY_DESIGN_LIMITATION', ...
        'uniqueRootCauseConfirmed', false);
    fprintf('[RESULT] FS_OMEGA_0P5_MAX_ASPECT_RATIO = %.9g\n', ...
        fsWorstAspect);
    fprintf('[RESULT] BOTTOM_OMEGA_2_MIN_ANGLE_DEG = %.9g\n', ...
        bottomMinimumAngle);
    fprintf('[RESULT] BOTTOM_SINGLE_CENTER_FAN = %s\n', ...
        yes_no(bottomSingleCenterFan));
    fprintf('[RESULT] METRIC_BUG = NO\n');
    fprintf('[RESULT] ROOT_CAUSE = NOT_YET_UNIQUE\n');
end

