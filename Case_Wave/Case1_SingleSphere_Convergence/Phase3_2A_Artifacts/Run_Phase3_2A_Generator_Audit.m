function row = panel_record(definition, specification, truncation, ...
        componentName, mesh, details, panelIndex, eventType, rankIndex, ...
        waterlineCount)
    [region, ringIndex, sectorIndex, scheduler] = classify_panel( ...
        specification, truncation, componentName, panelIndex, ...
        waterlineCount);
    vertices = reshape(mesh.vertices(panelIndex, :, :), 4, 3);
    row = empty_panel_record();
    row.mesh_level = specification.level.name;
    row.omega_rad_s = specification.omegaRadPerS;
    row.component = componentName;
    row.event_type = eventType;
    row.event_rank = rankIndex;
    row.panel_id = panelIndex;
    row.generator_region = region;
    row.ring_index = ringIndex;
    row.sector_index = sectorIndex;
    row.scheduler = scheduler;
    row.is_triangle = details.is_triangle(panelIndex);
    row.is_poor = details.is_poor(panelIndex);
    row.area_m2 = details.area_m2(panelIndex);
    row.sqrt_area_m = sqrt(details.area_m2(panelIndex));
    row.aspect_ratio = details.aspect_ratio(panelIndex);
    row.aspect_limit = details.aspect_limit(panelIndex);
    row.minimum_angle_deg = details.minimum_angle_deg(panelIndex);
    row.maximum_angle_deg = details.maximum_angle_deg(panelIndex);
    row.skewness_deg = details.skewness_deg(panelIndex);
    row.warp_deg = details.warp_deg(panelIndex);
    row.center_x_m = details.center_x_m(panelIndex);
    row.center_y_m = details.center_y_m(panelIndex);
    row.center_z_m = details.center_z_m(panelIndex);
    for vertexIndex = 1:4
        row.(sprintf('v%d_x_m', vertexIndex)) = vertices(vertexIndex, 1);
        row.(sprintf('v%d_y_m', vertexIndex)) = vertices(vertexIndex, 2);
        row.(sprintf('v%d_z_m', vertexIndex)) = vertices(vertexIndex, 3);
    end
    row.body_division_count = specification.level.bodyDivision;
    row.fs_radial_counts = join(string( ...
        specification.level.fsRadialCounts), '|');
    row.bottom_radial_counts = join(string( ...
        specification.level.bottomRadialCounts), '|');
    row.configured_wall_theta_count = ...
        specification.level.wallThetaCount;
    row.legacy_theta_count = truncation.legacyThetaNodeCount;
    row.final_wall_theta_count = truncation.commonOuterThetaNodeCount;
    row.radial_scheduler_candidate = classify_candidate(region);
    row.metric_bug = "NO";
    row.root_cause_status = "NOT_YET_UNIQUE";
    row.runtime_provenance = "PASS_CURRENT_WORKTREE";
    assert(~contains(lower(specification.configFile), ...
        lower(definition.originalRepository)), ...
        'CRESTU:Phase32APanelDiagnosticPath', ...
        'A diagnostic case path points to the original repository.');
end

function [region, ringIndex, sectorIndex, scheduler] = classify_panel( ...
        specification, truncation, componentName, panelIndex, ...
        waterlineCount)
    before = truncation.componentPanelCountsBefore;
    ringIndex = NaN;
    sectorIndex = NaN;
    scheduler = "not-applicable";
    if componentName == "body"
        region = "BODY_SURFACE";
        return
    elseif componentName == "farfield"
        region = "FARFIELD_STRUCTURED_WALL";
        scheduler = "build_frustum_wall equal-count rings";
        return
    end
    if componentName == "free_surface"
        baseRingPanels = before(1);
        if panelIndex <= baseRingPanels
            region = "FS_BASE_EQUAL_COUNT_POLAR_RING";
            ringIndex = ceil(panelIndex / waterlineCount);
            sectorIndex = mod(panelIndex - 1, waterlineCount) + 1;
            scheduler = "generate_free_surface_bmf radial weights + elliptic smoothing";
        else
            region = "FS_OUTER_TRUNCATION_TRANSITION";
            scheduler = "prepare_horizontal_surface + zipper_annulus";
        end
        return
    end

    bottomRingPanels = sum(specification.level.bottomRadialCounts) * ...
        waterlineCount;
    if panelIndex <= bottomRingPanels
        region = "BOTTOM_MIRRORED_FS_POLAR_RING";
        ringIndex = ceil(panelIndex / waterlineCount);
        sectorIndex = mod(panelIndex - 1, waterlineCount) + 1;
        scheduler = "bottomReferenceSurface mirrored from FS producer";
    elseif panelIndex <= before(2)
        localIndex = panelIndex - bottomRingPanels;
        [blockName, blockRing] = bottom_block(localIndex, waterlineCount);
        region = blockName;
        ringIndex = blockRing;
        scheduler = "generate_seabed_mesh adaptive 5-block structured infill";
    else
        region = "BOTTOM_OUTER_TRUNCATION_TRANSITION";
        scheduler = "prepare_horizontal_surface + zipper_annulus";
    end
end

function [blockName, blockRing] = bottom_block(localIndex, waterlineCount)
    quarterCount = waterlineCount / 4;
    Nx = max(2, round(quarterCount));
    Ny = Nx;
    Nr = max(3, round((Nx + Ny) * 0.25));
    sideBlockCount = Nx * Nr;
    if localIndex <= 4 * sideBlockCount
        blockIndex = ceil(localIndex / sideBlockCount);
        blockName = "BOTTOM_STRUCTURED_SIDE_BLOCK_" + string(blockIndex);
        withinBlock = mod(localIndex - 1, sideBlockCount) + 1;
        blockRing = ceil(withinBlock / Nr);
    else
        blockName = "BOTTOM_STRUCTURED_CENTRAL_PATCH";
        withinBlock = localIndex - 4 * sideBlockCount;
        blockRing = ceil(withinBlock / Ny);
    end
end

function candidate = classify_candidate(region)
    if contains(region, "BASE_EQUAL_COUNT_POLAR_RING") || ...
            contains(region, "MIRRORED_FS_POLAR_RING")
        candidate = "RADIAL_GRADING_OR_FIXED_RING_COUNT";
    elseif contains(region, "STRUCTURED")
        candidate = "FIVE_BLOCK_CORE_MAPPING_OR_ROUNDING";
    elseif contains(region, "TRUNCATION_TRANSITION")
        candidate = "COUNT_TRANSITION_OR_ZIPPER";
    else
        candidate = "NOT_CLASSIFIED";
    end
end

function rows = append_transition_records(rows, specification, domain, truncation)
    boundaries = [20.0, truncation.legacyRadiusM]; % [m]
    boundaryNames = ["MESH_TRANSITION_RADIUS"; "LEGACY_TRUNCATION_RADIUS"];
    meshes = {domain.fs, domain.seabed};
    componentNames = ["free_surface"; "bottom"];
    allH = zeros(0, 1);
    for componentIndex = 1:numel(meshes)
        mesh = meshes{componentIndex};
        vertices = reshape(mesh.vertices, mesh.n_panels, 4, 3);
        vertexRadius = hypot(vertices(:, :, 1), vertices(:, :, 2));
        for boundaryIndex = 1:numel(boundaries)
            radiusM = boundaries(boundaryIndex);
            mask = min(vertexRadius, [], 2) <= radiusM + 1.0e-8 & ...
                max(vertexRadius, [], 2) >= radiusM - 1.0e-8;
            h = sqrt(mesh.areas(mask));
            allH = [allH; h]; %#ok<AGROW>
            rows(end + 1, 1) = transition_record(specification, ...
                componentNames(componentIndex), boundaryNames(boundaryIndex), ...
                radiusM, h); %#ok<AGROW>
        end
    end
    rows(end + 1, 1) = transition_record(specification, "combined", ...
        "V4_COMBINED_TRANSITION_DEFINITION", NaN, allH);
end

function row = transition_record(specification, component, boundaryName, ...
        boundaryRadiusM, h)
    row = empty_transition_record();
    row.mesh_level = specification.level.name;
    row.omega_rad_s = specification.omegaRadPerS;
    row.component = component;
    row.boundary = boundaryName;
    row.boundary_radius_m = boundaryRadiusM;
    row.panel_count = numel(h);
    row.minimum_sqrt_area_m = min(h);
    row.maximum_sqrt_area_m = max(h);
    row.mean_sqrt_area_m = mean(h);
    row.median_sqrt_area_m = median(h);
    row.body_division_count = specification.level.bodyDivision;
    row.fs_radial_counts = join(string( ...
        specification.level.fsRadialCounts), '|');
    row.bottom_radial_counts = join(string( ...
        specification.level.bottomRadialCounts), '|');
end

function assert_runtime_scope(definition, specification, domain)
    paths = [string(specification.configFile); ...
        string(specification.bodyFile); string(domain.cfg.files.fs); ...
        string(domain.cfg.files.seabed); string(domain.cfg.files.farfield)];
    runtimePrefix = lower(string(specification.runtimeDirectory) + filesep);
    for index = 1:numel(paths)
        normalized = lower(strrep(paths(index), '/', filesep));
        assert(startsWith(normalized, runtimePrefix) && ...
            ~contains(normalized, lower(definition.originalRepository)), ...
            'CRESTU:Phase32AGeneratorRuntimeScope', ...
            'A generator audit path escaped the isolated current-worktree case.');
    end
end

