function summary = Finalize_Phase3_2A()
% FINALIZE_PHASE3_2A Generate final status, review, and Git/file audits.

    %% Stage 1: Re-read and assert every authoritative evidence table

    definition = phase32a.initialize();
    artifact = definition.artifactDirectory;
    fixtures = readtable(fullfile(artifact, ...
        'Phase3_2A_Quality_Metric_Unit_Tests.csv'), 'TextType', 'string');
    reconciliation = readtable(fullfile(artifact, ...
        'Phase3_2A_V4_Quality_Reconciliation.csv'), 'TextType', 'string');
    endpoint = readtable(fullfile(artifact, ...
        'Phase3_2A_Endpoint_Prototype_Quality.csv'), 'TextType', 'string');
    v5Manifest = readtable(fullfile(artifact, ...
        'Phase3_2A_V5_Mesh_Manifest.csv'), 'TextType', 'string');
    v5Quality = readtable(fullfile(artifact, ...
        'Phase3_2A_V5_Mesh_Quality.csv'), 'TextType', 'string');
    v5Isolation = readtable(fullfile(artifact, ...
        'Phase3_2A_V5_Control_Isolation.csv'), 'TextType', 'string');
    legacy = readtable(fullfile(artifact, ...
        'Phase3_2A_Legacy_Regression.csv'), 'TextType', 'string');
    bridge = readtable(fullfile(artifact, ...
        'Phase3_2A_BEM_Bridge_Smoke.csv'), 'TextType', 'string');
    integrity = readtable(fullfile(definition.convergenceDirectory, ...
        'Phase3_2_Artifacts', 'Phase3_2_Final_Report_Integrity.csv'));

    assert(height(fixtures) == 6 && all(fixtures.test_pass), ...
        'CRESTU:Phase32AFinalFixtures', 'Analytic quality fixtures are not 6/6 PASS.');
    assert(height(reconciliation) == 72 && all(reconciliation.row_match) && ...
        nnz(reconciliation.recomputed_status == "PASS") == 36 && ...
        nnz(reconciliation.recomputed_status == "FAIL") == 36, ...
        'CRESTU:Phase32AFinalReconciliation', ...
        'Blocked-v4 quality reconciliation is not 72/72 with 36/36 split.');
    assert(height(endpoint) == 24 && ...
        all(endpoint.component_gate_status == "PASS"), ...
        'CRESTU:Phase32AFinalEndpoint', 'Endpoint quality is not 24/24 PASS.');
    assert(height(v5Manifest) == 18 && height(v5Quality) == 72 && ...
        all(v5Quality.component_gate_status == "PASS") && ...
        height(v5Isolation) == 6 && ...
        all(v5Isolation.frequency_geometry_gate == "PASS"), ...
        'CRESTU:Phase32AFinalV5', 'V5 mesh evidence is not 18/72/6 all PASS.');
    assert(height(legacy) == 5 && all(legacy.exact_hash_regression), ...
        'CRESTU:Phase32AFinalLegacy', 'LEGACY exact regression is not 5/5 PASS.');
    assert(height(bridge) == 2 && all(bridge.solve_status == "PASS") && ...
        bridge.legacy_regression_status(1) == "PASS", ...
        'CRESTU:Phase32AFinalBridge', 'Limited BEM bridge is not 2/2 PASS.');
    assert(integrity.COMPONENT_QUALITY_ROWS_TOTAL == 72 && ...
        integrity.COMPONENT_QUALITY_ROWS_PASS == 36 && ...
        integrity.COMPONENT_QUALITY_ROWS_FAIL == 36, ...
        'CRESTU:Phase32AFinalTask0', 'Task 0 integrity evidence is not 72/36/36.');
    assert_preserved_fail_evidence(definition);

    %% Stage 2: Final status and reviewer gate

    finalStatus = build_final_status();
    writetable(finalStatus, fullfile(artifact, 'Phase3_2A_Final_Status.csv'));
    reviewer = build_reviewer_gate();
    writetable(reviewer, fullfile(artifact, 'Phase3_2A_Reviewer_Gate.csv'));
    write_main_report(definition, fixtures, reconciliation, endpoint, ...
        v5Manifest, v5Quality, v5Isolation, legacy, bridge);
    write_human_review(definition);
    write_git_audits(definition);

    summary = struct('schemaVersion', 1, ...
        'overallStatus', 'PASS_WITH_LIMITATIONS', ...
        'qualityMetricFixturesPass', true, ...
        'endpointQualityPassCount', 24, 'v5QualityPassCount', 72, ...
        'v5GeometryCaseCount', 18, 'bemBridgePassCount', 2, ...
        'legacyExactRegressionPassCount', 5, 'reviewerBlockers', 0, ...
        'readyForPhase32BSentinel', true, ...
        'readyForProduction', false, 'physicalValidation', 'PARTIAL');
    fprintf('[RESULT] PHASE3_2A_OVERALL = PASS_WITH_LIMITATIONS\n');
    fprintf('[RESULT] REVIEWER_BLOCKERS = 0\n');
    fprintf('[RESULT] READY_FOR_PHASE3_2B_SENTINEL = YES\n');
    fprintf('[RESULT] READY_FOR_PRODUCTION = NO\n');
end

