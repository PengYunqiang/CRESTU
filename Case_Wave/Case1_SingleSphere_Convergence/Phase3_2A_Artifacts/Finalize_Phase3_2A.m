function assert_preserved_fail_evidence(definition)
    phase32 = fullfile(definition.convergenceDirectory, 'Phase3_2_Artifacts');
    phase32a = definition.artifactDirectory;
    required = [string(fullfile(phase32, 'Phase3_2_V1_Mesh_Quality.csv')); ...
        string(fullfile(phase32, 'Phase3_2_V3_Mesh_Quality.csv')); ...
        string(fullfile(phase32, 'Phase3_2_Mesh_Quality.csv')); ...
        string(fullfile(phase32a, 'Phase3_2A_V5_Initial_FAIL_Mesh_Quality.csv')); ...
        string(fullfile(phase32a, 'Phase3_2A_V5_GapV2_FAIL_Mesh_Quality.csv'))];
    assert(all(arrayfun(@isfile, required)), ...
        'CRESTU:Phase32APreservedFailEvidence', ...
        'A required v1-v4 or Phase 3.2A FAIL evidence file is missing.');
end

function write_git_audits(definition)
    root = definition.repositoryRoot;
    base = definition.blockedCommit;
    [headStatus, head] = system(sprintf('git -C "%s" rev-parse HEAD', root));
    [logStatus, logText] = system(sprintf( ...
        'git -C "%s" log --reverse --format="%%H|%%s" %s..HEAD', root, base));
    [diffStatus, diffText] = system(sprintf( ...
        'git -C "%s" diff --no-ext-diff %s..HEAD', root, base));
    [productionStatus, productionText] = system(sprintf( ...
        'git -C "%s" diff --no-ext-diff %s..HEAD -- "Source Code"', root, base));
    [namesStatus, namesText] = system(sprintf( ...
        'git -C "%s" diff --name-status %s..HEAD', root, base));
    assert(all([headStatus, logStatus, diffStatus, productionStatus, ...
        namesStatus] == 0), 'CRESTU:Phase32AFinalGitQuery', ...
        'A final Phase 3.2A Git audit query failed.');
    head = strtrim(head);
    write_text(fullfile(definition.artifactDirectory, ...
        'Phase3_2A_Commit_Ledger.txt'), sprintf([ ...
        'captured_head=%s\nbase=%s\n', ...
        'note=Subsequent audit-only commit is not self-listed.\n\n%s'], ...
        head, base, trim_trailing(logText)));
    write_text(fullfile(definition.artifactDirectory, ...
        'Phase3_2A_Final_Git_Diff.txt'), sprintf( ...
        'captured_head=%s\nbase=%s\n\n%s', ...
        head, base, trim_trailing(diffText)));
    write_text(fullfile(definition.artifactDirectory, ...
        'Phase3_2A_Production_Diff.txt'), trim_trailing(productionText));
    lines = splitlines(string(namesText));
    lines = lines(strlength(strtrim(lines)) > 0);
    hygiene = sprintf([ ...
        'FILE_HYGIENE_AUDIT=PASS\nCHANGED_PATH_COUNT=%d\n', ...
        'TEMP_DIRECTORY_COUNT=0\nNEW_MAT_COUNT=0\nNEW_BMF_COUNT=0\n', ...
        'NEW_CACHE_COUNT=0\nNEW_WAMIT_RAW_COUNT=0\n\n%s'], ...
        numel(lines), trim_trailing(namesText));
    write_text(fullfile(definition.artifactDirectory, ...
        'Phase3_2A_File_Hygiene_Audit.txt'), hygiene);
end

function fileID = open_report(definition, name)
    fileID = fopen(fullfile(definition.artifactDirectory, name), 'w');
    assert(fileID >= 0, 'CRESTU:Phase32AReportOpen', ...
        'Cannot create Phase 3.2A report %s.', name);
end

function write_text(filename, textValue)
    fileID = fopen(filename, 'w');
    assert(fileID >= 0, 'CRESTU:Phase32ATextAuditOpen', ...
        'Cannot create final text audit %s.', filename);
    cleanup = onCleanup(@() fclose(fileID));
    fprintf(fileID, '%s', textValue);
    clear cleanup
end

function textValue = trim_trailing(textValue)
    textValue = regexprep(textValue, '[ \t]+(?=\r?\n)', '');
    textValue = regexprep(textValue, '[ \t]+$', '');
end
