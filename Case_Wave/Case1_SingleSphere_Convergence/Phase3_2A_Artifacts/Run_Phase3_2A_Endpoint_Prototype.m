        'finite_positive_geometry', false, 'duplicate_panel_count', 0, ...
        'component_gate_pass', false, 'component_gate_status', "NOT_RUN", ...
        'requested_near_radial_step_m', NaN, ...
        'realized_near_radial_step_m', NaN, ...
        'requested_outer_radial_step_max_m', NaN, ...
        'realized_outer_radial_step_m', NaN, ...
        'configured_outer_radial_layer_count', 0, ...
        'realized_outer_radial_layer_count', 0, ...
        'base_theta_count', 0, 'final_wall_theta_count', 0, ...
        'requested_bottom_core_radial_layer_count', 0, ...
