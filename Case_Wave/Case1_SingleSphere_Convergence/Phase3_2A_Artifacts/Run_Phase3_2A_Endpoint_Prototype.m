        'bottom_connector_maximum_aspect_ratio', NaN, ...
        'transition_median_sqrt_area_m', NaN, ...
        'manifold_status', "NOT_RUN", 'orientation_status', "NOT_RUN", ...
        'waterline_status', "NOT_RUN", ...
        'self_intersection_status', "NOT_RUN", ...
        'actual_top_outer_radius_m', NaN, ...
        'actual_bottom_outer_radius_m', NaN, ...
        'combined_geometry_hash', "", 'production_source_hash', "", ...
        'runtime_provenance', "", 'error_identifier', "", ...
        'error_message', "");
end

function tableOut = endpoint_failure_row(specification, exception)
    row = endpoint_quality_row();
    row.mesh_level = specification.level.name;
    row.mesh_level_index = specification.level.index;
    row.omega_rad_s = specification.omegaRadPerS;
    row.topology_mode = "QUALITY_CONTROLLED_V2";
    row.component = "case_build";
    row.component_gate_status = "FAIL";
    row.error_identifier = string(exception.identifier);
    row.error_message = string(exception.message);
    tableOut = struct2table(row);
end

function combined = append_table(combined, current)
    if isempty(combined)
        combined = current;
    else
        combined = [combined; current];
    end
end

function assert_runtime_scope(definition, specification, domain)
    paths = [string(specification.configFile); string(specification.bodyFile); ...
        string(domain.cfg.files.fs); string(domain.cfg.files.seabed); ...
        string(domain.cfg.files.farfield)];
    runtimePrefix = lower(string(specification.runtimeDirectory) + filesep);
    for index = 1:numel(paths)
        normalized = lower(strrep(paths(index), '/', filesep));
        assert(startsWith(normalized, runtimePrefix) && ...
            ~contains(normalized, lower(definition.originalRepository)), ...
            'CRESTU:Phase32AEndpointRuntimeScope', ...
            'Endpoint prototype path escaped the isolated current-worktree case.');
    end
end

function text = pass_fail(value)
    if value
        text = "PASS";
    else
        text = "FAIL";
    end
end
