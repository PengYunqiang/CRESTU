function fingerprint = audit_fingerprint(paths, localFrequencies, ...
        fixedFrequencies, raoFrequencies, baselineCfg)
    codeVersion = get_rankine_code_version();
    runnerFile = [mfilename('fullpath'), '.m'];
    runnerSHA256 = sha256_file_hash(runnerFile);
    baselineConfigSHA256 = sha256_file_hash(paths.phase2_3BaselineConfig);
    formalConfigSHA256 = sha256_file_hash(paths.formalFrequencyConfig);
    geometryControls = struct( ...
        'fsRadialCounts', [baselineCfg.fs.nr_near, baselineCfg.fs.nr_sponge], ...
        'outerVerticalPanelCount', baselineCfg.fs.nz_farfield, ...
        'outerTruncationTopQ', baselineCfg.outer_truncation.topRadiusPerWavelength, ...
        'outerTruncationBottomQ', baselineCfg.outer_truncation.bottomRadiusPerWavelength, ...
        'isx', baselineCfg.isx, 'isy', baselineCfg.isy, ...
        'waterDepthM', baselineCfg.water_depth);
    payload = struct('schemaVersion', 1, ...
        'runnerVersion', 'Phase3.1B-root-cause-audit-v1', ...
        'runnerSHA256', runnerSHA256, ...
        'productionDependencySHA256', codeVersion.fingerprint, ...
        'baselineConfigSHA256', baselineConfigSHA256, ...
        'formalConfigSHA256', formalConfigSHA256, ...
        'geometryControls', geometryControls, ...
        'localFrequenciesRadPerS', localFrequencies, ...
        'fixedFrequenciesRadPerS', fixedFrequencies, ...
        'raoFrequenciesRadPerS', raoFrequencies);
    fingerprint = struct('schemaVersion', 1, ...
        'runnerVersion', "Phase3.1B-root-cause-audit-v1", ...
        'runnerSHA256', string(runnerSHA256), ...
        'productionDependencySHA256', string(codeVersion.fingerprint), ...
        'baselineConfigSHA256', string(baselineConfigSHA256), ...
        'formalConfigSHA256', string(formalConfigSHA256), ...
        'geometryControlSHA256', string(sha256_hash(jsonencode(geometryControls))), ...
        'frequencyListSHA256', string(sha256_hash(jsonencode(struct( ...
            'local', localFrequencies, 'fixed', fixedFrequencies, ...
            'rao', raoFrequencies)))), ...
        'combinedSHA256', string(sha256_hash(jsonencode(payload))));
end

function [records, payloads] = initialize_checkpoint_records(frequencies, ...
        checkpoint, fingerprint, forceRecompute)
    records = repmat(empty_record(), numel(frequencies), 1);
    payloads = cell(numel(frequencies), 1);
    for index = 1:numel(frequencies)
        records(index).omega_rad_s = frequencies(index);
    end
    if forceRecompute || ~isfile(checkpoint)
        return
    end
    loaded = load(checkpoint, 'localRecords', 'localPayloads', ...
        'raoRecords', 'raoPayloads', 'localFrequencies', 'raoFrequencies', ...
        'checkpointFingerprint');
    if isfield(loaded, 'localRecords')
        candidateRecords = loaded.localRecords;
        candidatePayloads = loaded.localPayloads;
    elseif isfield(loaded, 'raoRecords')
        candidateRecords = loaded.raoRecords;
        candidatePayloads = loaded.raoPayloads;
    else
        fprintf('[WARN] CHECKPOINT_REUSE = FORBIDDEN | missing record payload: %s\n', ...
            checkpoint);
        return
    end
    frequencyMatch = numel(candidateRecords) == numel(frequencies) && ...
        max(abs(reshape([candidateRecords.omega_rad_s], 1, []) - ...
        frequencies)) <= 64 * eps(max(frequencies));
    fingerprintMatch = isfield(loaded, 'checkpointFingerprint') && ...
        string(loaded.checkpointFingerprint) == string(fingerprint);
    if frequencyMatch && fingerprintMatch
        records = candidateRecords;
        payloads = candidatePayloads;
    else
        fprintf(['[WARN] CHECKPOINT_REUSE = FORBIDDEN | source/config/', ...
            'frequency fingerprint mismatch: %s\n'], checkpoint);
    end
end

function matched = checkpoint_matches(loaded, fingerprint, frequencies, ...
        recordField)
    matched = isfield(loaded, recordField) && ...
        isfield(loaded, 'checkpointFingerprint') && ...
        string(loaded.checkpointFingerprint) == string(fingerprint);
    if ~matched
        fprintf('[WARN] CHECKPOINT_REUSE = FORBIDDEN | fingerprint mismatch.\n');
        return
    end
    records = loaded.(recordField);
    matched = numel(records) == numel(frequencies) && ...
        max(abs(reshape([records.omega_rad_s], 1, []) - frequencies)) <= ...
        64 * eps(max(frequencies));
    if ~matched
        fprintf('[WARN] CHECKPOINT_REUSE = FORBIDDEN | frequency mismatch.\n');
    end
end

function [record, payload] = run_isolated_case(omega, persistFullPhi, ...
        baselineCfg, formalCfg, paths)
    runtimeDirectory = tempname;
    mkdir(runtimeDirectory);
    cleanup = onCleanup(@() remove_runtime_directory(runtimeDirectory));
    caseName = sprintf('Phase3_1B_w%04d', round(1000 * omega));
    configFile = fullfile(runtimeDirectory, [caseName, '.cfg']);
    write_runtime_config(configFile, caseName, omega, baselineCfg, ...
        formalCfg, persistFullPhi);
    results = run_frequency_domain_case(configFile, ...
        'skipPhysicalDiagnostics', true);
    [record, payload] = extract_frequency_record(results, 1, ...
        persistFullPhi, "REMESHED", paths);
    clear cleanup
end

function [records, payloads] = run_fixed_geometry_case(frequencies, anchor, ...
        baselineCfg, formalCfg, paths)
    runtimeDirectory = tempname;
    mkdir(runtimeDirectory);
    cleanup = onCleanup(@() remove_runtime_directory(runtimeDirectory));
    caseName = 'Phase3_1B_FixedGeometry_w0600';
    configFile = fullfile(runtimeDirectory, [caseName, '.cfg']);
    write_runtime_config(configFile, caseName, anchor, baselineCfg, ...
        formalCfg, true);
    results = run_frequency_domain_case(configFile, ...
        'physicsFrequenciesRadPerS', frequencies, ...
        'fixedGeometryAnchorRadPerS', anchor, ...
        'skipPhysicalDiagnostics', true);
    records = repmat(empty_record(), numel(frequencies), 1);
    payloads = cell(numel(frequencies), 1);
    for index = 1:numel(frequencies)
        [records(index), payloads{index}] = extract_frequency_record( ...
            results, index, true, "FIXED_GEOMETRY", paths);
    end
    geometryHashes = string({records.combined_geometry_hash});
    assert(numel(unique(geometryHashes)) == 1 && ...
        string(results.audit.diagnosticState.fixedGeometrySHA256) == ...
        geometryHashes(1), 'CRESTU:Phase31BFixedGeometryHash', ...
        'Fixed-geometry diagnostic did not retain one exact geometry hash.');
    clear cleanup
end

function [record, payload] = extract_frequency_record(results, index, ...
        persistFullPhi, geometryMode, paths)
    record = empty_record();
    omega = results.omegas(index); % [rad/s]
    loaded = load(results.potential_cache_file, 'pot_cache');
    entry = loaded.pot_cache.entries(index);
    audit = results.audit.frequencyEntries(index);
    diagnostics = results.diagnostics(index);
    conditioning = cellfun(@(item) item.conditioning, ...
        entry.solver_diagnostics, 'UniformOutput', false);
    truncation = entry.assembly_info{1}.outer_truncation;
    outer = entry.assembly_info{1}.outer_absorbing_boundary;
    phiBody = entry.phi_rad_body(:, 3); % Heave radiation [m^2/s]
    bodyMesh = load_transformed_body_mesh(results.config);
    areas = reshape(bodyMesh.areas, [], 1); % [m^2]
    assert(numel(areas) == numel(phiBody), ...
        'CRESTU:Phase31BBodyShape', ...
        'Body areas and heave radiation potential have different lengths.');
    nj3 = results.generalized_normals(:, 3);
    panelGeneralizedForce = 1i * omega * results.config.rho .* ...
        phiBody .* nj3 .* areas; % [N] for unit heave displacement
    forceFromPanels = sum(panelGeneralizedForce);
    forceFromProduction = diagnostics.radiation_force(3, 3);
    forceMismatch = abs(forceFromPanels - forceFromProduction) / ...
        max([abs(forceFromPanels), abs(forceFromProduction), eps]);
    assert(forceMismatch <= 1.0e-12, 'CRESTU:Phase31BForceLineage', ...
        'Reconstructed raw F33 differs from the production diagnostic.');

    [minimumArea, maximumArea, minimumAspect, maximumAspect] = ...
        active_geometry_quality(results.config);
    maximumPhiIndex = find(abs(phiBody) == max(abs(phiBody)), 1);
    probeIndices = unique([1, round(numel(phiBody) / 2), numel(phiBody)], ...
        'stable');
    if numel(probeIndices) < 3
        probeIndices(end + 1:3) = probeIndices(end);
    end
    record.omega_rad_s = omega;
    record.geometry_mode = geometryMode;
    record.physical_k_per_m = outer.physicalKPerM;
    record.wavelength_m = 2 * pi / outer.physicalKPerM;
    record.kappa_real_per_m = outer.kappaRealPerM;
    record.kappa_imag_per_m = outer.kappaImagPerM;
    record.phi3_norm = norm(phiBody);
    record.phi3_area_weighted_norm = sqrt(sum(abs(phiBody) .^ 2 .* areas));
    record.phi3_max_abs = abs(phiBody(maximumPhiIndex));
    record.phi3_phase_at_max_deg = angle(phiBody(maximumPhiIndex)) * 180 / pi;
    record.phi3_probe1_real = real(phiBody(probeIndices(1)));
    record.phi3_probe1_imag = imag(phiBody(probeIndices(1)));
    record.phi3_probe2_real = real(phiBody(probeIndices(2)));
    record.phi3_probe2_imag = imag(phiBody(probeIndices(2)));
    record.phi3_probe3_real = real(phiBody(probeIndices(3)));
    record.phi3_probe3_imag = imag(phiBody(probeIndices(3)));
    record.F33_rad_real_N = real(forceFromProduction);
    record.F33_rad_imag_N = imag(forceFromProduction);
    record.F33_rad_abs_N = abs(forceFromProduction);
    record.F33_rad_angle_deg = angle(forceFromProduction) * 180 / pi;
    record.F33_panel_reconstruction_relative_error = forceMismatch;
    record.A33_kg = results.added_mass(3, 3, index);
    record.B33_kg_s = results.damping(3, 3, index);
    record.F3_real_N_per_m = real(results.excitation(3, 1, index));
    record.F3_imag_N_per_m = imag(results.excitation(3, 1, index));
    response = results.rao.complex(3, 1, index);
    denominator = results.rao.dynamic_matrix(3, 3, index);
    record.RAO3_real_m_per_m = real(response);
    record.RAO3_imag_m_per_m = imag(response);
    record.RAO3_abs_m_per_m = abs(response);
    record.RAO3_phase_deg = angle(response) * 180 / pi;
    record.D3_real_N_per_m = real(denominator);
    record.D3_imag_N_per_m = imag(denominator);
    record.D3_abs_N_per_m = abs(denominator);
    record.raw_rcond = min(cellfun(@(item) item.rawRcondEstimate, conditioning));
    record.scaled_rcond = min(cellfun(@(item) item.scaledRcondEstimate, conditioning));
    record.relative_residual = max(cellfun(@(item) ...
        item.radiationRelativeResidual, entry.solver_diagnostics));
    record.body_panel_count = audit.bodyPanelCount;
    record.free_surface_panel_count = audit.freeSurfacePanelCount;
    record.bottom_panel_count = audit.bottomPanelCount;
    record.farfield_panel_count = audit.outerBoundaryPanelCount;
    record.total_panel_count = audit.bemUnknownCount;
    record.outer_radius_top_m = truncation.effectiveTopRadiusM;
    record.outer_radius_bottom_m = truncation.effectiveBottomRadiusM;
    record.legacy_theta_count = truncation.legacyThetaNodeCount;
    record.top_theta_ideal_count = truncation.topThetaCountSelection.idealCount;
    record.top_theta_candidate_count = truncation.topThetaCountSelection.candidateCount;
    record.top_theta_count = truncation.topOuterThetaNodeCount;
    record.bottom_theta_ideal_count = truncation.bottomThetaCountSelection.idealCount;
    record.bottom_theta_candidate_count = truncation.bottomThetaCountSelection.candidateCount;
    record.bottom_theta_count = truncation.bottomOuterThetaNodeCount;
    record.common_wall_theta_count = truncation.commonOuterThetaNodeCount;
    record.top_radial_ideal_count = max(0, ...
        (truncation.effectiveTopRadiusM - truncation.legacyRadiusM) / ...
        truncation.topSurfaceDerived.radialTargetM);
    record.top_radial_layer_count = truncation.topSurfaceDerived.radialLayerCount;
    record.bottom_radial_ideal_count = max(0, ...
        (truncation.effectiveBottomRadiusM - truncation.legacyRadiusM) / ...
        truncation.bottomSurfaceDerived.radialTargetM);
    record.bottom_radial_layer_count = ...
        truncation.bottomSurfaceDerived.radialLayerCount;
    record.wall_vertical_ideal_count = ...
        truncation.wallDerived.countSelection.idealCount;
    record.wall_vertical_candidate_count = ...
        truncation.wallDerived.countSelection.candidateCount;
    record.wall_vertical_layer_count = ...
        truncation.wallDerived.verticalLayerCount;
    record.top_theta_spacing_m = ...
        truncation.topThetaCountSelection.chosenSpacingM;
    record.bottom_theta_spacing_m = ...
        truncation.bottomThetaCountSelection.chosenSpacingM;
    record.top_radial_spacing_m = ...
        truncation.topSurfaceDerived.maximumRadialStep;
    record.bottom_radial_spacing_m = ...
        truncation.bottomSurfaceDerived.maximumRadialStep;
    record.wall_slant_spacing_m = ...
        truncation.wallDerived.maximumSlantStep;
    record.minimum_panel_area_m2 = minimumArea;
    record.maximum_panel_area_m2 = maximumArea;
    record.minimum_panel_aspect_ratio = minimumAspect;
    record.maximum_panel_aspect_ratio = maximumAspect;
    record.body_geometry_hash = string(entry.mesh_audit.body.hash);
    record.free_surface_geometry_hash = string(entry.mesh_audit.freeSurface.hash);
    record.bottom_geometry_hash = string(entry.mesh_audit.bottom.hash);
    record.farfield_geometry_hash = string(entry.mesh_audit.outerBoundary.hash);
    record.combined_geometry_hash = string(entry.mesh_audit.geometry.hash);
    record.status = "PASS";

    fullPhi = complex(zeros(0, 1));
    if persistFullPhi
        rawFile = results.config.files.raw_diagnostics;
        assert(isfile(rawFile), 'CRESTU:Phase31BRawPhiMissing', ...
            'PERSIST_FULL_PHI did not create its bound raw diagnostic MAT.');
        raw = load(rawFile, 'rawDiagnosticSolutions');
        radiationRecords = raw.rawDiagnosticSolutions(cellfun(@(item) ...
            strcmp(item.problemName, 'radiation') && ...
            any(item.columnIndices == 3) && ...
            abs(item.omegaRadPerS - omega) <= 64 * eps(max(1, omega)), ...
            raw.rawDiagnosticSolutions));
        assert(numel(radiationRecords) == 1, ...
            'CRESTU:Phase31BRawPhiShape', ...
            'Expected one full heave-radiation solution record.');
        item = radiationRecords{1};
        localColumn = find(item.columnIndices == 3, 1);
        fullPhi = item.solutionPhi(:, localColumn);
        assert(string(item.geometrySHA256) == record.combined_geometry_hash, ...
            'CRESTU:Phase31BRawPhiHash', ...
            'Full potential geometry hash differs from the active solve.');
    end
    payload = struct('omega_rad_s', omega, ...
        'geometry_mode', geometryMode, ...
        'harmonic_convention', "exp(+i*omega*t)", ...
        'prescribed_heave_displacement_amplitude_m', 1.0, ...
        'prescribed_heave_velocity', "i*omega*n3", ...
        'pressure_formula', "p=-i*rho*omega*phi3", ...
        'generalized_force_formula', "F33=i*omega*rho*sum(n3*phi3*dS)", ...
        'A33_formula', "A33=real(F33)/omega^2", ...
        'B33_formula', "B33=-imag(F33)/omega", ...
        'body_phi3', phiBody, 'full_phi3', fullPhi, ...
        'panel_generalized_force', panelGeneralizedForce, ...
        'probe_indices', probeIndices, ...
        'combined_geometry_hash', record.combined_geometry_hash, ...
        'production_dependency_fingerprint', ...
            string(results.audit.codeVersion.fingerprint), ...
        'repository_root', string(paths.repositoryRoot));
end

function bodyMesh = load_transformed_body_mesh(cfg)
    bodyMesh = read_bmf(cfg.bodies(1).mesh_file);
    bodyMesh = transform_body_mesh(bodyMesh, cfg.bodies(1));
    bodyMesh = reduce_mesh_by_symmetry(bodyMesh, cfg.isx, cfg.isy, cfg.z_tol);
end

function [minimumArea, maximumArea, minimumAspect, maximumAspect] = ...
        active_geometry_quality(cfg)
    meshes = {load_transformed_body_mesh(cfg), read_bmf(cfg.files.fs), ...
        read_bmf(cfg.files.seabed), read_bmf(cfg.files.farfield)};
