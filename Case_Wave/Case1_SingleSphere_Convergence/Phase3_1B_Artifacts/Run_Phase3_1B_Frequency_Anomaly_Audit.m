function ratios = panel_aspect_ratio(mesh)
    vertices = reshape(mesh.vertices, mesh.n_panels, 4, 3);
    ratios = ones(mesh.n_panels, 1);
    for panelIndex = 1:mesh.n_panels
        panel = reshape(vertices(panelIndex, :, :), 4, 3);
        edges = sqrt(sum((panel([2, 3, 4, 1], :) - panel) .^ 2, 2));
        edges = edges(edges > 1.0e-13);
        ratios(panelIndex) = max(edges) / min(edges);
    end
end

