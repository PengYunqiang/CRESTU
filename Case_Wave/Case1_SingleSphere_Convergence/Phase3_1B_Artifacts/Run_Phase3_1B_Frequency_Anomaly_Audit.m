function tableOut = build_rao_denominator_table(tableIn)
    response = complex(tableIn.RAO3_real_m_per_m, ...
        tableIn.RAO3_imag_m_per_m);
    excitation = complex(tableIn.F3_real_N_per_m, ...
        tableIn.F3_imag_N_per_m);
    unwrappedPhaseDeg = unwrap(angle(response)) * 180 / pi;
    amplitudeScale = max(abs(response));
    amplitudeFloor = max(1.0e-6 * amplitudeScale, eps);
    normalizedComplexStep = [NaN; abs(diff(response)) ./ max( ...
        [abs(response(1:end - 1)), abs(response(2:end)), ...
        repmat(amplitudeFloor, numel(response) - 1, 1)], [], 2)];
    amplitudeRelativeStep = [NaN; abs(diff(abs(response))) ./ max( ...
        [abs(response(1:end - 1)), abs(response(2:end)), ...
        repmat(amplitudeFloor, numel(response) - 1, 1)], [], 2)];
    phaseProtected = abs(response) < amplitudeFloor | ...
        abs(excitation) < max(1.0e-6 * max(abs(excitation)), eps);
    tableOut = tableIn(:, {'omega_rad_s', 'F3_real_N_per_m', ...
        'F3_imag_N_per_m', 'A33_kg', 'B33_kg_s', ...
        'RAO3_real_m_per_m', 'RAO3_imag_m_per_m', ...
        'RAO3_abs_m_per_m', 'RAO3_phase_deg', 'D3_real_N_per_m', ...
        'D3_imag_N_per_m', 'D3_abs_N_per_m', 'raw_rcond', ...
        'scaled_rcond', 'relative_residual'});
    tableOut.RAO3_unwrapped_phase_deg = unwrappedPhaseDeg;
    tableOut.RAO3_normalized_complex_step = normalizedComplexStep;
    tableOut.RAO3_amplitude_relative_step = amplitudeRelativeStep;
    tableOut.phase_blocking_protected = phaseProtected;
end

function tableOut = build_reference_comparison(localTable, raoTable, paths)
    radiation = read_wamit_first_order(fullfile(paths.wamitIrr3Directory, ...
        'hemisphere.1'), 1025);
    excitation = read_wamit_excitation(fullfile(paths.wamitIrr3Directory, ...
        'hemisphere.2'), 1025, 9.80665, 1, 1);
    response = read_wamit_rao(fullfile(paths.wamitIrr3Directory, ...
        'hemisphere.4'));
    radiationOmega = reshape(radiation.omegas, [], 1);
    excitationOmega = reshape(excitation.omegas, [], 1);
    responseOmega = reshape(response.omegas, [], 1);
    heading0 = find(abs(excitation.headings) < 1.0e-12, 1);
    responseHeading0 = find(abs(response.headings) < 1.0e-12, 1);
    targetRadiation = [0.58; 0.60; 0.62];
    targetRao = [1.36; 1.40; 1.44];
    rows = cell(numel(targetRadiation) + numel(targetRao), 1);
    for index = 1:numel(targetRadiation)
        omega = targetRadiation(index);
        localIndex = find(abs(localTable.omega_rad_s - omega) <= ...
            64 * eps(max(1, omega)), 1);
        wamitA33 = interp1(radiationOmega, ...
            squeeze(radiation.added_mass(3, 3, :)), omega, 'pchip');
        wamitB33 = interp1(radiationOmega, ...
            squeeze(radiation.damping(3, 3, :)), omega, 'pchip');
        rows{index} = table(omega, "RADIATION", ...
            localTable.A33_kg(localIndex), localTable.B33_kg_s(localIndex), ...
            NaN, NaN, wamitA33, wamitB33, NaN, NaN, ...
            reference_method(radiationOmega, omega), ...
            'VariableNames', {'omega_rad_s', 'comparison_type', ...
            'CRESTU_A33_kg', 'CRESTU_B33_kg_s', ...
            'CRESTU_F3_abs_N_per_m', 'CRESTU_RAO3_abs_m_per_m', ...
            'WAMIT_A33_kg', 'WAMIT_B33_kg_s', ...
            'WAMIT_F3_abs_N_per_m', 'WAMIT_RAO3_abs_m_per_m', ...
            'reference_method'});
    end
    for index = 1:numel(targetRao)
        omega = targetRao(index);
        localIndex = find(abs(raoTable.omega_rad_s - omega) <= ...
            64 * eps(max(1, omega)), 1);
        wamitF3 = interp1(excitationOmega, squeeze(abs( ...
            excitation.force(3, heading0, :))), omega, 'pchip');
        wamitRao3 = interp1(responseOmega, squeeze( ...
            response.amplitude(3, responseHeading0, :)), omega, 'pchip');
        rows{numel(targetRadiation) + index} = table(omega, "RAO", ...
            NaN, NaN, hypot(raoTable.F3_real_N_per_m(localIndex), ...
            raoTable.F3_imag_N_per_m(localIndex)), ...
            raoTable.RAO3_abs_m_per_m(localIndex), NaN, NaN, ...
            wamitF3, wamitRao3, reference_method(responseOmega, omega), ...
            'VariableNames', rows{1}.Properties.VariableNames);
    end
    tableOut = vertcat(rows{:});
end

function method = reference_method(referenceOmega, targetOmega)
    if any(abs(referenceOmega - targetOmega) <= 64 * eps(max(1, targetOmega)))
        method = "EXACT_REFERENCE_FREQUENCY";
    else
        method = "PCHIP_DIAGNOSTIC_INTERPOLATION_NO_TUNING";
    end
end

function decisions = classify_results(localTable, comparisonTable, raoTable)
    remeshedPhiDeviation = isolated_deviation(localTable.omega_rad_s, ...
        complex(localTable.phi3_probe2_real, localTable.phi3_probe2_imag), 0.60);
    remeshedForceDeviation = isolated_deviation(localTable.omega_rad_s, ...
        complex(localTable.F33_rad_real_N, localTable.F33_rad_imag_N), 0.60);
    remeshedADeviation = isolated_deviation(localTable.omega_rad_s, ...
        localTable.A33_kg, 0.60);
    remeshedBDeviation = isolated_deviation(localTable.omega_rad_s, ...
        localTable.B33_kg_s, 0.60);
    fixedForce = complex(comparisonTable.F33_fixed_real_N, ...
        comparisonTable.F33_fixed_imag_N);
    fixedForceDeviation = isolated_deviation(comparisonTable.omega_rad_s, ...
        fixedForce, 0.60);
    fixedADeviation = isolated_deviation(comparisonTable.omega_rad_s, ...
        comparisonTable.A33_fixed_kg, 0.60);
    fixedBDeviation = isolated_deviation(comparisonTable.omega_rad_s, ...
        comparisonTable.B33_fixed_kg_s, 0.60);
    remeshAnomaly = max([remeshedForceDeviation, remeshedADeviation, ...
        remeshedBDeviation]) > 0.50;
    fixedAnomaly = max([fixedForceDeviation, fixedADeviation, ...
        fixedBDeviation]) > 0.50;
    meshHashes = string(localTable.combined_geometry_hash);
    meshDiscontinuity = numel(unique(meshHashes)) > 1;
    if remeshedPhiDeviation > 0.50
        firstLayer = "POTENTIAL";
    elseif remeshedForceDeviation > 0.50
        firstLayer = "RAW_FORCE";
    elseif max(remeshedADeviation, remeshedBDeviation) > 0.50
        firstLayer = "AB_EXTRACTION";
    else
        firstLayer = "UNRESOLVED";
    end
    if remeshAnomaly && ~fixedAnomaly
        causal = "YES";
        firstLayer = "DISCRETIZATION";
    elseif ~remeshAnomaly
        causal = "NO";
    else
        causal = "UNRESOLVED";
    end

    [minimumDenominator, minimumIndex] = min(raoTable.D3_abs_N_per_m);
    maximumResponse = max(raoTable.RAO3_abs_m_per_m);
    responseAtMinD = raoTable.RAO3_abs_m_per_m(minimumIndex);
    denseFinite = all(isfinite([raoTable.RAO3_real_m_per_m; ...
        raoTable.RAO3_imag_m_per_m; raoTable.D3_abs_N_per_m]));
    maximumComplexStep = max(raoTable.RAO3_normalized_complex_step, ...
        [], 'omitnan');
    if denseFinite && responseAtMinD >= 0.8 * maximumResponse && ...
            minimumDenominator < median(raoTable.D3_abs_N_per_m) && ...
            maximumComplexStep < 1.0
        raoClassification = "PHYSICAL_RESONANCE";
    elseif denseFinite && any(raoTable.phase_blocking_protected)
        raoClassification = "NEAR_ZERO_PHASE_ARTIFACT";
    elseif ~denseFinite || maximumComplexStep >= 1.0
        raoClassification = "NUMERICAL_DISCONTINUITY";
    else
        raoClassification = "UNRESOLVED";
    end
    decisions = struct( ...
        'omega0p6FirstAnomalousLayer', firstLayer, ...
        'remeshedPhiDeviation', remeshedPhiDeviation, ...
        'remeshedRawForceDeviation', remeshedForceDeviation, ...
        'remeshedA33Deviation', remeshedADeviation, ...
        'remeshedB33Deviation', remeshedBDeviation, ...
        'fixedRawForceDeviation', fixedForceDeviation, ...
        'fixedA33Deviation', fixedADeviation, ...
        'fixedB33Deviation', fixedBDeviation, ...
        'anomalyPresentWithRemesh', yes_no(remeshAnomaly), ...
        'anomalyPresentWithFixedGeometry', yes_no(fixedAnomaly), ...
        'frequencyLocalMeshDiscontinuity', yes_no(meshDiscontinuity), ...
        'frequencyLocalDiscretizationCausal', causal, ...
        'omega1p4Rao3Classification', raoClassification, ...
        'minimumD3AbsNPerM', minimumDenominator, ...
        'omegaAtMinimumD3RadPerS', raoTable.omega_rad_s(minimumIndex), ...
        'maximumDenseRaoNormalizedComplexStep', maximumComplexStep);
end

function deviation = isolated_deviation(omega, values, target)
    targetIndex = find(abs(omega - target) <= 64 * eps(max(1, target)), 1);
    assert(~isempty(targetIndex) && targetIndex > 1 && ...
        targetIndex < numel(omega), 'CRESTU:Phase31BTargetInterior', ...
        'The isolated-deviation target must be an interior frequency.');
    weight = (omega(targetIndex) - omega(targetIndex - 1)) / ...
        (omega(targetIndex + 1) - omega(targetIndex - 1));
    predicted = values(targetIndex - 1) + weight * ...
        (values(targetIndex + 1) - values(targetIndex - 1));
    scale = max(abs(values));
    floorValue = max(1.0e-6 * scale, eps);
    deviation = abs(values(targetIndex) - predicted) / max( ...
        [abs(values(targetIndex)), abs(predicted), floorValue]);
end

