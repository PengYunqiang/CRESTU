function summary = Run_Phase3_1B_Frequency_Anomaly_Audit(forceRecompute)
% RUN_PHASE3_1B_FREQUENCY_ANOMALY_AUDIT Isolate 0.6/1.4 response anomalies.
%
% This diagnostic runner never edits WAMIT data and never applies curve
% smoothing.  Remeshed cases use the ordinary production call.  The
% fixed-geometry arm uses the explicit, default-off diagnostic option of
% run_frequency_domain_case and freezes the complete omega=0.60 geometry.

    arguments
        forceRecompute (1, 1) logical = false
    end

    %% Stage 1: Resolve frozen inputs and bind every checkpoint to provenance

    paths = initialize_paths();
    add_production_paths(paths);
    baselineCfg = read_config(paths.phase2_3BaselineConfig);
    formalCfg = read_config(paths.formalFrequencyConfig);
    localFrequencies = [0.54, 0.56, 0.58, 0.59, 0.60, ...
        0.61, 0.62, 0.64, 0.66]; % [rad/s]
    lineageFrequencies = [0.58, 0.59, 0.60, 0.61, 0.62]; % [rad/s]
    fixedFrequencies = [0.56, 0.58, 0.59, 0.60, 0.61, 0.62, 0.64]; % [rad/s]
    raoFrequencies = 1.30:0.02:1.50; % [rad/s]
    fingerprint = audit_fingerprint(paths, localFrequencies, ...
        fixedFrequencies, raoFrequencies, baselineCfg);
    writetable(struct2table(fingerprint), fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Run_Fingerprint.csv'));

    %% Stage 2: Run isolated frequency-local production cases near 0.6

    localCheckpoint = fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Local_Checkpoint.mat');
    [localRecords, localPayloads] = initialize_checkpoint_records( ...
        localFrequencies, localCheckpoint, fingerprint.combinedSHA256, ...
        forceRecompute);
    for frequencyIndex = 1:numel(localFrequencies)
        if localRecords(frequencyIndex).status == "PASS"
            fprintf('[INFO] Reuse fingerprint-matched local checkpoint | omega=%.6g rad/s\n', ...
                localFrequencies(frequencyIndex));
            continue
        end
        omega = localFrequencies(frequencyIndex); % [rad/s]
        fprintf('[INFO] Phase 3.1B remeshed local %d/%d | omega=%.6g rad/s\n', ...
            frequencyIndex, numel(localFrequencies), omega);
        [localRecords(frequencyIndex), localPayloads{frequencyIndex}] = ...
            run_isolated_case(omega, true, baselineCfg, formalCfg, paths);
        checkpointFingerprint = fingerprint.combinedSHA256; %#ok<NASGU>
        save(localCheckpoint, 'localRecords', 'localPayloads', ...
            'localFrequencies', 'checkpointFingerprint', '-v7.3');
    end
    assert(all([localRecords.status] == "PASS"), ...
        'CRESTU:Phase31BLocalSolve', ...
        'One or more 0.6-neighborhood production cases failed.');
    localTable = struct2table(localRecords);
    writetable(localTable, fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Local_Dense_Sweep.csv'));
    write_lineage_artifacts(localTable, localPayloads, lineageFrequencies, ...
        paths.artifactDirectory);
    write_discretization_ledger(localTable, paths.artifactDirectory);

    %% Stage 3: Freeze the complete omega=0.60 production geometry

    fixedCheckpoint = fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Fixed_Geometry_Checkpoint.mat');
    fixedRecords = repmat(empty_record(), numel(fixedFrequencies), 1);
    fixedPayloads = cell(numel(fixedFrequencies), 1);
    fixedLoaded = false;
    if ~forceRecompute && isfile(fixedCheckpoint)
        loaded = load(fixedCheckpoint, 'fixedRecords', 'fixedPayloads', ...
            'fixedFrequencies', 'checkpointFingerprint');
        fixedLoaded = checkpoint_matches(loaded, ...
            fingerprint.combinedSHA256, fixedFrequencies, 'fixedRecords');
        if fixedLoaded
            fixedRecords = loaded.fixedRecords;
            fixedPayloads = loaded.fixedPayloads;
            fprintf('[INFO] Reuse fingerprint-matched fixed-geometry checkpoint.\n');
        end
    end
    if ~fixedLoaded
        [fixedRecords, fixedPayloads] = run_fixed_geometry_case( ...
            fixedFrequencies, 0.60, baselineCfg, formalCfg, paths);
        checkpointFingerprint = fingerprint.combinedSHA256; %#ok<NASGU>
        save(fixedCheckpoint, 'fixedRecords', 'fixedPayloads', ...
            'fixedFrequencies', 'checkpointFingerprint', '-v7.3');
    end
    assert(all([fixedRecords.status] == "PASS"), ...
        'CRESTU:Phase31BFixedSolve', ...
        'One or more fixed-geometry cases failed.');
    fixedTable = struct2table(fixedRecords);
    comparisonTable = build_fixed_geometry_comparison( ...
        localTable, fixedTable, fixedFrequencies);
    writetable(comparisonTable, fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Fixed_Geometry_Comparison.csv'));

    %% Stage 4: Independently audit the dense heave response around 1.4

    raoCheckpoint = fullfile(paths.artifactDirectory, ...
        'Phase3_1B_RAO3_Checkpoint.mat');
    [raoRecords, raoPayloads] = initialize_checkpoint_records( ...
        raoFrequencies, raoCheckpoint, fingerprint.combinedSHA256, ...
        forceRecompute);
    for frequencyIndex = 1:numel(raoFrequencies)
        if raoRecords(frequencyIndex).status == "PASS"
            fprintf('[INFO] Reuse fingerprint-matched RAO checkpoint | omega=%.6g rad/s\n', ...
                raoFrequencies(frequencyIndex));
            continue
        end
        omega = raoFrequencies(frequencyIndex); % [rad/s]
        fprintf('[INFO] Phase 3.1B RAO dense sweep %d/%d | omega=%.6g rad/s\n', ...
            frequencyIndex, numel(raoFrequencies), omega);
        [raoRecords(frequencyIndex), raoPayloads{frequencyIndex}] = ...
            run_isolated_case(omega, false, baselineCfg, formalCfg, paths);
        checkpointFingerprint = fingerprint.combinedSHA256; %#ok<NASGU>
        save(raoCheckpoint, 'raoRecords', 'raoPayloads', ...
            'raoFrequencies', 'checkpointFingerprint', '-v7.3');
    end
    assert(all([raoRecords.status] == "PASS"), ...
        'CRESTU:Phase31BRAOSolve', ...
        'One or more 1.4-neighborhood production cases failed.');
    raoTable = build_rao_denominator_table(struct2table(raoRecords));
    writetable(raoTable, fullfile(paths.artifactDirectory, ...
        'Phase3_1B_RAO3_Denominator_Audit.csv'));

    %% Stage 5: Read-only WAMIT spot checks and machine-readable decisions

    referenceTable = build_reference_comparison(localTable, raoTable, paths);
    writetable(referenceTable, fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Targeted_Reference_Comparison.csv'));
    decisions = classify_results(localTable, comparisonTable, raoTable);
    writetable(struct2table(decisions), fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Provisional_Decisions.csv'));
    sourceAfter = production_source_snapshot(paths);
    writetable(sourceAfter, fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Production_Source_SHA256_After_Diagnostics.csv'));

    summary = struct('schemaVersion', 1, 'fingerprint', fingerprint, ...
        'localTable', localTable, 'fixedTable', fixedTable, ...
        'comparisonTable', comparisonTable, 'raoTable', raoTable, ...
        'referenceTable', referenceTable, 'decisions', decisions, ...
        'sourceAfterDiagnostics', sourceAfter);
    save(fullfile(paths.artifactDirectory, ...
        'Phase3_1B_Diagnostic_Result.mat'), 'summary', '-v7.3');
    fprintf('[RESULT] OMEGA_0P6_FIRST_ANOMALOUS_LAYER = %s\n', ...
        decisions.omega0p6FirstAnomalousLayer);
    fprintf('[RESULT] FREQUENCY_LOCAL_DISCRETIZATION_CAUSAL = %s\n', ...
        decisions.frequencyLocalDiscretizationCausal);
    fprintf('[RESULT] OMEGA_1P4_RAO3_CLASSIFICATION = %s\n', ...
        decisions.omega1p4Rao3Classification);
end

function paths = initialize_paths()
    artifactDirectory = fileparts(mfilename('fullpath'));
    convergenceDirectory = fileparts(artifactDirectory);
    caseWaveDirectory = fileparts(convergenceDirectory);
    repositoryRoot = fileparts(caseWaveDirectory);
    versionDirectory = fileparts(fileparts(repositoryRoot));
    paths = struct('artifactDirectory', artifactDirectory, ...
        'convergenceDirectory', convergenceDirectory, ...
        'caseWaveDirectory', caseWaveDirectory, ...
        'repositoryRoot', repositoryRoot, ...
        'sourceDirectory', fullfile(repositoryRoot, 'Source Code'), ...
        'formalFrequencyConfig', fullfile(convergenceDirectory, ...
            'Mesh_Fine', 'Case1_Fine.cfg'), ...
        'phase2_3BaselineConfig', fullfile(convergenceDirectory, ...
            'Phase2_2_Artifacts', 'Tests', 'Frustum_Instrumentation', ...
            'Cases', 'Frustum_Top_Only.cfg'), ...
        'wamitIrr3Directory', fullfile(versionDirectory, 'WAMIT', ...
            'FullSphereIRR3'));
    required = {paths.formalFrequencyConfig, paths.phase2_3BaselineConfig, ...
        fullfile(paths.wamitIrr3Directory, 'hemisphere.1'), ...
        fullfile(paths.wamitIrr3Directory, 'hemisphere.2'), ...
        fullfile(paths.wamitIrr3Directory, 'hemisphere.4')};
    assert(all(cellfun(@isfile, required)), ...
        'CRESTU:Phase31BRequiredInput', ...
        'A frozen config or read-only WAMIT reference is missing.');
end

