function normals = diagonal_cross_normals(vertices)
    panelCount = size(vertices, 1);
    normals = NaN(panelCount, 3);
    for panelIndex = 1:panelCount
        panel = reshape(vertices(panelIndex, :, :), 4, 3);
        areaVector = cross(panel(3, :) - panel(1, :), ...
            panel(4, :) - panel(2, :));
        magnitude = norm(areaVector);
        assert(isfinite(magnitude) && magnitude > 0, ...
            'CRESTU:Phase23DegeneratePanel', ...
            'Panel %d has a zero diagonal-cross area.', panelIndex);
        normals(panelIndex, :) = areaVector / magnitude;
    end
end

function normals = benchmark_first_triple_normals(vertices)
% Replicate the normal algorithm in the Phase 2.2 Hankel benchmark.
    panelCount = size(vertices, 1);
    normals = NaN(panelCount, 3);
    for panelIndex = 1:panelCount
        panel = reshape(vertices(panelIndex, :, :), 4, 3);
        uniquePanel = unique_panel_vertices(panel);
        found = false;
        for firstIndex = 1:(size(uniquePanel, 1) - 2)
            for secondIndex = (firstIndex + 1):(size(uniquePanel, 1) - 1)
                for thirdIndex = (secondIndex + 1):size(uniquePanel, 1)
                    candidate = cross( ...
                        uniquePanel(secondIndex, :) - uniquePanel(firstIndex, :), ...
                        uniquePanel(thirdIndex, :) - uniquePanel(firstIndex, :));
                    magnitude = norm(candidate);
                    if magnitude > 1e-14
                        normals(panelIndex, :) = candidate / magnitude;
                        found = true;
                        break
                    end
                end
                if found
                    break
                end
            end
            if found
                break
            end
        end
        assert(found, 'CRESTU:Phase23BenchmarkNormal', ...
            'Panel %d has no non-collinear winding triple.', panelIndex);
    end
end

function uniquePanel = unique_panel_vertices(panel)
    uniquePanel = zeros(4, 3);
    uniqueCount = 0;
    for vertexIndex = 1:4
        if uniqueCount == 0 || all(max(abs(uniquePanel(1:uniqueCount, :) - ...
                panel(vertexIndex, :)), [], 2) > 1e-12)
            uniqueCount = uniqueCount + 1;
            uniquePanel(uniqueCount, :) = panel(vertexIndex, :);
        end
    end
    uniquePanel = uniquePanel(1:uniqueCount, :);
end

function pass = structured_wall_connectivity_pass(nodeIds, thetaCount, layerCount)
    pass = size(nodeIds, 1) == thetaCount * layerCount;
    if ~pass
        return
    end
    for layerIndex = 1:layerCount
        rows = (layerIndex - 1) * thetaCount + (1:thetaCount);
        nextRows = rows([2:end, 1]);
        pass = pass && all(nodeIds(rows, 2) == nodeIds(nextRows, 1)) && ...
            all(nodeIds(rows, 3) == nodeIds(nextRows, 4));
        if layerIndex < layerCount
            lowerRows = rows + thetaCount;
            pass = pass && all(nodeIds(rows, 4) == nodeIds(lowerRows, 1)) && ...
                all(nodeIds(rows, 3) == nodeIds(lowerRows, 2));
        end
    end
end

