function legacy = read_legacy_benchmark_bmf(fileName)
% Reproduce the Phase 2.2 benchmark parser, including unique-vertex centers.
    fileId = fopen(fileName, 'r');
    assert(fileId >= 0, 'CRESTU:Phase23LegacyOpen', ...
        'Cannot open legacy benchmark BMF: %s', fileName);
    cleanup = onCleanup(@() fclose(fileId));
    header = fgetl(fileId);
    line2 = textscan(fgetl(fileId), '%f %d');
    textscan(fgetl(fileId), '%d %d');
    panelCount = sscanf(fgetl(fileId), '%d', 1);
    vertices = zeros(panelCount, 4, 3);
    for panelIndex = 1:panelCount
        for vertexIndex = 1:4
            line = fgetl(fileId);
            while ischar(line) && isempty(strtrim(line))
                line = fgetl(fileId);
            end
            xyz = sscanf(line, '%f', 3);
            assert(numel(xyz) == 3, 'CRESTU:Phase23LegacyVertex', ...
                'Legacy panel %d vertex %d is invalid.', ...
                panelIndex, vertexIndex);
            vertices(panelIndex, vertexIndex, :) = reshape(xyz, 1, 1, 3);
        end
    end
    centers = zeros(panelCount, 3);
    for panelIndex = 1:panelCount
        centers(panelIndex, :) = mean(unique_panel_vertices(reshape( ...
            vertices(panelIndex, :, :), 4, 3)), 1);
    end
    normals = benchmark_first_triple_normals(vertices);
    legacy = struct('file', fileName, 'header', strtrim(header), ...
        'panelType', double(line2{2}), 'panelCount', panelCount, ...
        'vertices', vertices, 'centers', centers, 'normals', normals);
end

