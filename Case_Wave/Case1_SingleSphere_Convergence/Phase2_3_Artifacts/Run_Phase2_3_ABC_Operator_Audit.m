function ntheta = cylindrical_ntheta(centers, normals)
    radius = hypot(centers(:, 1), centers(:, 2));
    tangentialUnit = [-centers(:, 2) ./ radius, ...
        centers(:, 1) ./ radius, zeros(size(radius))];
    ntheta = sum(normals .* tangentialUnit, 2);
end

function components = hankel_components(centers, normals, mode, kappa, ...
        waterDepth, actualGamma)
    radius = hypot(centers(:, 1), centers(:, 2));
    theta = atan2(centers(:, 2), centers(:, 1));
    z = centers(:, 3);
    radialUnit = [cos(theta), sin(theta), zeros(size(radius))];
    tangentialUnit = [-sin(theta), cos(theta), zeros(size(radius))];
    radialNormal = sum(normals .* radialUnit, 2);
    tangentialNormal = sum(normals .* tangentialUnit, 2);
    verticalNormal = normals(:, 3);

    argument = kappa .* radius;
    hankel = besselh(mode, 2, argument);
    hankelNext = besselh(mode + 1, 2, argument);
    hankelPrime = (mode ./ argument) .* hankel - hankelNext;
    phase = exp(1i * mode .* theta);
    verticalFactor = cosh(kappa .* (z + waterDepth)) ./ ...
        cosh(kappa * waterDepth);
    phi = hankel .* phase .* verticalFactor;
    radialDerivative = kappa .* hankelPrime .* phase .* verticalFactor;
    thetaDerivative = 1i * mode .* phi;
    verticalDerivative = kappa .* tanh(kappa .* (z + waterDepth)) .* phi;
    fullExact = radialNormal .* radialDerivative + ...
        (tangentialNormal ./ radius) .* thetaDerivative + ...
        verticalNormal .* verticalDerivative;
    exactMeridional = radialNormal .* radialDerivative + ...
        verticalNormal .* verticalDerivative;
    analyticGamma = (-radialNormal) .* ...
        (1i * kappa + 1 ./ (2 .* radius)) + ...
        verticalNormal .* kappa .* tanh(kappa .* (z + waterDepth));
    analyticProduction = analyticGamma .* phi;
    actualProduction = actualGamma .* phi;
    components = struct('Phi', phi, 'radialDerivative', radialDerivative, ...
        'thetaDerivative', thetaDerivative, ...
        'verticalDerivative', verticalDerivative, 'fullExact', fullExact, ...
        'exactMeridional', exactMeridional, ...
        'analyticProduction', analyticProduction, ...
        'actualProduction', actualProduction, ...
        'analyticGamma', analyticGamma, 'actualGamma', actualGamma, ...
        'radialNormal', radialNormal, ...
        'tangentialNormal', tangentialNormal, ...
        'verticalNormal', verticalNormal, ...
        'kPhiScale', abs(kappa .* phi));
end

function gamma = analytic_production_gamma(centers, normals, kappa, waterDepth)
    radius = hypot(centers(:, 1), centers(:, 2));
    radialNormal = (normals(:, 1) .* centers(:, 1) + ...
        normals(:, 2) .* centers(:, 2)) ./ radius;
    verticalNormal = normals(:, 3);
    gamma = (-radialNormal) .* (1i * kappa + 1 ./ (2 .* radius)) + ...
        verticalNormal .* kappa .* tanh(kappa .* ...
        (centers(:, 3) + waterDepth));
end

function metrics = error_metrics(errorValues, firstReference, ...
        secondReference, kPhiScale, areas)
% Use a field-scale floor so local derivative cancellation cannot inflate error.
    absoluteError = abs(errorValues(:));
    pointScale = max([abs(firstReference(:)), abs(secondReference(:)), ...
        kPhiScale(:)], [], 2);
    globalFloor = 1e-12 * max([pointScale(:); 1e-300]);
    denominator = max(pointScale, globalFloor);
    relativeError = absoluteError ./ denominator;
    weights = areas(:);
    assert(all(isfinite(weights) & weights > 0), ...
        'CRESTU:Phase23MetricWeights', ...
        'Hankel benchmark areas must be finite and positive.');
    numeratorL2 = sqrt(sum(weights .* absoluteError .^ 2));
    denominatorL2 = max([sqrt(sum(weights .* abs(firstReference(:)) .^ 2)), ...
        sqrt(sum(weights .* abs(secondReference(:)) .^ 2)), ...
        sqrt(sum(weights .* kPhiScale(:) .^ 2)), ...
        globalFloor * sqrt(sum(weights))]);
    metrics = struct( ...
        'maxAbsolute', max(absoluteError), ...
        'p95Absolute', percentile(absoluteError, 95), ...
        'weightedL2Absolute', sqrt(sum(weights .* absoluteError .^ 2) / ...
            sum(weights)), ...
        'maxRelative', max(relativeError), ...
        'p95Relative', percentile(relativeError, 95), ...
        'weightedL2Relative', numeratorL2 / denominatorL2, ...
        'minimumDenominator', min(denominator), ...
        'globalDenominatorFloor', globalFloor);
end

function metrics = cylinder_coefficient_metrics(centers, mode, kappa, areas)
% Radius-only oracle for the expected O((kappa*r)^-2) truncation scaling.
    radius = hypot(centers(:, 1), centers(:, 2));
    argument = kappa .* radius;
    hankel = besselh(mode, 2, argument);
    hankelNext = besselh(mode + 1, 2, argument);
    hankelPrime = (mode ./ argument) .* hankel - hankelNext;
    exactInwardCoefficient = -kappa .* hankelPrime ./ hankel;
    asymptoticInwardCoefficient = 1i * kappa + 1 ./ (2 .* radius);
    metrics = error_metrics(exactInwardCoefficient - ...
        asymptoticInwardCoefficient, exactInwardCoefficient, ...
        asymptoticInwardCoefficient, ...
        repmat(abs(kappa), size(radius)), areas);
end

function value = percentile(values, percentage)
    values = sort(values(isfinite(values)));
    assert(~isempty(values), 'CRESTU:Phase23Percentile', ...
        'Cannot calculate a percentile from an empty finite vector.');
    if numel(values) == 1
        value = values(1);
        return
    end
    position = 1 + (numel(values) - 1) * percentage / 100;
    lowerIndex = floor(position);
    upperIndex = ceil(position);
    if lowerIndex == upperIndex
        value = values(lowerIndex);
    else
        value = values(lowerIndex) + (position - lowerIndex) * ...
            (values(upperIndex) - values(lowerIndex));
    end
end

