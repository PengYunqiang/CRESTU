        record.maximum_abs_outer_ntheta <= options.outerNormalTolerance && ...
        record.maximum_outer_column_residual <= options.outerColumnTolerance;
    if pass
        record.status = "PASS";
    else
        record.status = "FAIL";
        record.error_identifier = "CRESTU:Phase31NumericalGate";
        record.error_message = "Finite/rcond/residual/P_FULL assembly gate failed.";
    end
end

