function records = initialize_formal_records(frequencies, checkpoint, force, ...
        requiredFingerprint)
% INITIALIZE_FORMAL_RECORDS Reuse only an exact fingerprint-bound checkpoint.

    records = repmat(empty_record(), numel(frequencies), 1);
    for index = 1:numel(frequencies)
        records(index).omega_rad_s = frequencies(index);
        records(index).radius_factor = 1.0;
    end
    if force || ~isfile(checkpoint)
        return
    end
    loaded = load(checkpoint, 'formalRecords', 'frequencies', ...
        'checkpointFingerprint');
    fingerprintMatch = isfield(loaded, 'checkpointFingerprint') && ...
        string(loaded.checkpointFingerprint) == string(requiredFingerprint);
    if ~fingerprintMatch
        fprintf(['[WARN] CHECKPOINT_REUSE = FORBIDDEN | formal source/', ...
            'config/geometry/frequency/runner fingerprint mismatch.\n']);
        return
    end
    if isfield(loaded, 'formalRecords') && ...
            numel(loaded.formalRecords) == numel(frequencies) && ...
            max(abs(reshape([loaded.formalRecords.omega_rad_s], 1, []) - ...
            frequencies)) <= 64 * eps(max(frequencies))
        records = loaded.formalRecords;
    end
end

function record = run_one_production_case(omega, radiusFactor, qTop, qBottom, ...
        baselineCfg, formalCfg, options)
% RUN_ONE_PRODUCTION_CASE Run one timed, isolated, clean production solve.

    record = empty_record();
    record.omega_rad_s = omega;
    record.radius_factor = radiusFactor;
    record.q_top = qTop;
    record.q_bottom = qBottom;
    runtimeDirectory = tempname;
    mkdir(runtimeDirectory);
    cleanup = onCleanup(@() remove_runtime_directory(runtimeDirectory));
    caseName = sprintf('Phase3_1_w%04d_R%03d', ...
        round(1000 * omega), round(100 * radiusFactor));
    configFile = fullfile(runtimeDirectory, [caseName, '.cfg']);
    write_runtime_config(configFile, caseName, omega, qTop, qBottom, ...
        baselineCfg, formalCfg);
    timer = tic;

    try
        results = run_frequency_domain_case(configFile, ...
            'skipPhysicalDiagnostics', true);
        record.total_runtime_s = toc(timer);
        loaded = load(results.potential_cache_file, 'pot_cache');
        assert(isfield(loaded, 'pot_cache') && ...
            numel(loaded.pot_cache.entries) == 1, ...
            'CRESTU:Phase31PotentialCacheShape', ...
            'One-frequency Phase 3.1 cache has an invalid entry count.');
        entry = loaded.pot_cache.entries(1);
        record = extract_case_record(record, results, entry, options);
    catch exception
        record.total_runtime_s = toc(timer);
        record.status = "FAIL";
        record.error_identifier = string(exception.identifier);
        record.error_message = string(exception.message);
        fprintf('[FAIL] Phase 3.1 case omega=%.6g factor=%.3g | %s | %s\n', ...
            omega, radiusFactor, exception.identifier, exception.message);
    end
    clear cleanup
end

function record = extract_case_record(record, results, entry, options)
% EXTRACT_CASE_RECORD Extract production fields without relabeling diagnostics.

    solverDiagnostics = entry.solver_diagnostics;
    conditioning = cellfun(@(item) item.conditioning, solverDiagnostics, ...
        'UniformOutput', false);
    assembly = entry.assembly_info;
    outerSpecifications = cellfun(@(item) item.outer_absorbing_boundary, ...
        assembly, 'UniformOutput', false);
    truncation = assembly{1}.outer_truncation;
    outer = outerSpecifications{1};
    audit = results.audit.frequencyEntries(1);

    record.physical_k_per_m = outer.physicalKPerM;
    record.kappa_real_per_m = outer.kappaRealPerM;
    record.kappa_imag_per_m = outer.kappaImagPerM;
    record.top_radius_m = truncation.effectiveTopRadiusM;
    record.bottom_radius_m = truncation.effectiveBottomRadiusM;
    record.kR_top = record.physical_k_per_m * record.top_radius_m;
    record.kR_bottom = record.physical_k_per_m * record.bottom_radius_m;
    record.abs_kappa_R_top = hypot(record.kappa_real_per_m, ...
        record.kappa_imag_per_m) * record.top_radius_m;
    record.raw_rcond = min(cellfun(@(item) item.rawRcondEstimate, conditioning));
    record.scaled_rcond = min(cellfun(@(item) ...
        item.scaledRcondEstimate, conditioning));
    record.radiation_linear_relative_residual = max(cellfun(@(item) ...
        item.radiationRelativeResidual, solverDiagnostics));
    record.diffraction_linear_relative_residual = max(cellfun(@(item) ...
        item.diffractionRelativeResidual, solverDiagnostics));
    record.radiation_algebraic_relative_residual = max(cellfun(@(item) ...
        item.radiation.relativeResidualFrobeniusNorm, solverDiagnostics));
    record.diffraction_algebraic_relative_residual = max(cellfun(@(item) ...
        item.diffraction.relativeResidualFrobeniusNorm, solverDiagnostics));
    record.maximum_abs_outer_ntheta = max(cellfun(@(item) ...
        item.maximumAbsTangentialNormal, outerSpecifications));
    record.maximum_outer_column_residual = max(cellfun(@(item) ...
        item.outer_source_column_audit.reconstructionRelativeResidual, assembly));
    record.A33_raw_kg = results.added_mass_raw(3, 3, 1);
    record.A33_kg = results.added_mass(3, 3, 1);
    record.B33_raw_kg_s = results.damping_raw(3, 3, 1);
    record.B33_kg_s = results.damping(3, 3, 1);
    excitation = results.excitation(3, 1, 1); % Heave, heading 0 [N/m]
    response = results.rao.complex(3, 1, 1); % Heave RAO [m/m]
    record.F3_real_N_per_m = real(excitation);
    record.F3_imag_N_per_m = imag(excitation);
    record.F3_abs_N_per_m = abs(excitation);
    record.F3_phase_deg = angle(excitation) * 180 / pi;
    record.RAO3_real_m_per_m = real(response);
    record.RAO3_imag_m_per_m = imag(response);
    record.RAO3_abs_m_per_m = abs(response);
    record.RAO3_phase_deg = angle(response) * 180 / pi;
    record.RAO_matrix_rcond = results.rao.rcond(1);
    record.body_panel_count = audit.bodyPanelCount;
    record.free_surface_panel_count = audit.freeSurfacePanelCount;
    record.bottom_panel_count = audit.bottomPanelCount;
    record.farfield_panel_count = audit.outerBoundaryPanelCount;
    record.bem_unknown_count = audit.bemUnknownCount;
    record.body_geometry_hash = string(entry.mesh_audit.body.hash);
    record.free_surface_geometry_hash = ...
        string(entry.mesh_audit.freeSurface.hash);
    record.bottom_geometry_hash = string(entry.mesh_audit.bottom.hash);
    record.farfield_geometry_hash = ...
        string(entry.mesh_audit.outerBoundary.hash);
    record.combined_geometry_hash = string(entry.mesh_audit.geometry.hash);
    record.legacy_theta_count = truncation.legacyThetaNodeCount;
    record.top_theta_count = truncation.topOuterThetaNodeCount;
    record.bottom_theta_count = truncation.bottomOuterThetaNodeCount;
    record.common_wall_theta_count = truncation.commonOuterThetaNodeCount;
    record.top_radial_layer_count = ...
        truncation.topSurfaceDerived.radialLayerCount;
    record.bottom_radial_layer_count = ...
        truncation.bottomSurfaceDerived.radialLayerCount;
    record.wall_vertical_layer_count = ...
        truncation.wallDerived.verticalLayerCount;
    record.top_theta_spacing_m = ...
        truncation.topThetaCountSelection.chosenSpacingM;
    record.bottom_theta_spacing_m = ...
        truncation.bottomThetaCountSelection.chosenSpacingM;
    record.top_radial_spacing_m = ...
        truncation.topSurfaceDerived.maximumRadialStep;
    record.bottom_radial_spacing_m = ...
        truncation.bottomSurfaceDerived.maximumRadialStep;
    record.wall_slant_spacing_m = ...
        truncation.wallDerived.maximumSlantStep;
    record.assembly_runtime_s = sum(cellfun(@(item) item.elapsed_seconds, assembly));

    finiteValues = [record.physical_k_per_m, record.kappa_real_per_m, ...
        record.kappa_imag_per_m, record.raw_rcond, record.scaled_rcond, ...
        record.radiation_linear_relative_residual, ...
        record.diffraction_linear_relative_residual, ...
        record.radiation_algebraic_relative_residual, ...
        record.diffraction_algebraic_relative_residual, ...
        record.A33_kg, record.B33_kg_s, real(excitation), imag(excitation), ...
        real(response), imag(response)];
    residualMaximum = max([record.radiation_linear_relative_residual, ...
        record.diffraction_linear_relative_residual, ...
        record.radiation_algebraic_relative_residual, ...
        record.diffraction_algebraic_relative_residual]);
