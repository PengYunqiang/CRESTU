function [auditTable, pass] = audit_formal_curves(formalTable, options)
% AUDIT_FORMAL_CURVES Detect isolated spikes, sign flips, and phase jumps.

    omega = formalTable.omega_rad_s;
    metrics = { ...
        'A33', formalTable.A33_kg, false; ...
        'B33', formalTable.B33_kg_s, false; ...
        'F3_complex', complex(formalTable.F3_real_N_per_m, ...
            formalTable.F3_imag_N_per_m), true; ...
        'RAO3_complex', complex(formalTable.RAO3_real_m_per_m, ...
            formalTable.RAO3_imag_m_per_m), true};
    metricName = strings(size(metrics, 1), 1);
    maximumInteriorDeviation = NaN(size(metricName));
    omegaAtMaximumInteriorDeviation = NaN(size(metricName));
    maximumPhaseStepDeg = NaN(size(metricName));
    isolatedSignFlipCount = zeros(size(metricName));
    gatePass = false(size(metricName));

    for metricIndex = 1:size(metrics, 1)
        metricName(metricIndex) = string(metrics{metricIndex, 1});
        values = reshape(metrics{metricIndex, 2}, [], 1);
        scale = max(abs(values), [], 'omitnan');
        floorValue = max(options.responseFloorFraction * scale, eps);
        interior = NaN(size(values));
        for index = 2:numel(values) - 1
            interpolationWeight = (omega(index) - omega(index - 1)) / ...
                (omega(index + 1) - omega(index - 1));
            predicted = values(index - 1) + interpolationWeight * ...
                (values(index + 1) - values(index - 1));
            denominator = max([abs(values(index)), abs(predicted), floorValue]);
            interior(index) = abs(values(index) - predicted) / denominator;
        end
        [maximumInteriorDeviation(metricIndex), maximumIndex] = ...
            max(interior, [], 'omitnan');
        omegaAtMaximumInteriorDeviation(metricIndex) = omega(maximumIndex);

        if metrics{metricIndex, 3}
            valid = abs(values) >= floorValue;
            phase = unwrap(angle(values));
            phaseStep = abs(diff(phase)) * 180 / pi;
            validStep = valid(1:end - 1) & valid(2:end);
            if any(validStep)
                maximumPhaseStepDeg(metricIndex) = ...
                    max(phaseStep(validStep), [], 'omitnan');
            else
                maximumPhaseStepDeg(metricIndex) = 0;
            end
        else
            signs = sign(real(values));
            isolatedSignFlipCount(metricIndex) = sum(signs(2:end - 1) ~= 0 & ...
                signs(2:end - 1) ~= signs(1:end - 2) & ...
                signs(2:end - 1) ~= signs(3:end));
            maximumPhaseStepDeg(metricIndex) = 0;
        end
        gatePass(metricIndex) = ...
            maximumInteriorDeviation(metricIndex) <= ...
                options.maximumCurveInteriorDeviation && ...
            maximumPhaseStepDeg(metricIndex) <= options.maximumPhaseStepDeg && ...
            isolatedSignFlipCount(metricIndex) == 0;
    end
    auditTable = table(metricName, maximumInteriorDeviation, ...
        omegaAtMaximumInteriorDeviation, maximumPhaseStepDeg, ...
        isolatedSignFlipCount, gatePass);
    pass = all(gatePass);
end

function [auditTable, pass] = adjudicate_dense_phase3_1b_evidence( ...
        auditTable, preliminaryPass, paths, options)
% ADJUDICATE_DENSE_PHASE3_1B_EVIDENCE Resolve coarse-grid curvature only.
%
% The original gate and value remain persisted.  A failed coarse three-point
% curvature may pass only when a fingerprinted dense production sweep covers
% that frequency and its local complex/amplitude/denominator metrics pass.

    auditTable.preliminaryGatePass = auditTable.gatePass;
    auditTable.denseEvidenceStatus = repmat("NOT_REQUIRED", ...
        height(auditTable), 1);
    auditTable.denseEvidenceMetric = repmat("", height(auditTable), 1);
    auditTable.denseEvidenceValue = NaN(height(auditTable), 1);
    auditTable.denseEvidenceThreshold = NaN(height(auditTable), 1);
    auditTable.adjudicationNote = repmat("", height(auditTable), 1);
    if preliminaryPass
        pass = true;
        return
    end

    phase3_1bDirectory = fullfile(paths.convergenceDirectory, ...
        'Phase3_1B_Artifacts');
    localFile = fullfile(phase3_1bDirectory, ...
        'Phase3_1B_Local_Dense_Sweep.csv');
    raoFile = fullfile(phase3_1bDirectory, ...
        'Phase3_1B_RAO3_Denominator_Audit.csv');
    decisionFile = fullfile(phase3_1bDirectory, ...
        'Phase3_1B_Provisional_Decisions.csv');
    if ~all(cellfun(@isfile, {localFile, raoFile, decisionFile}))
        failed = ~auditTable.gatePass;
        auditTable.denseEvidenceStatus(failed) = "MISSING";
        auditTable.adjudicationNote(failed) = ...
            "Phase 3.1B dense evidence is unavailable; coarse failure retained.";
        pass = false;
        return
    end
    local = readtable(localFile);
    rao = readtable(raoFile);
    decisions = readtable(decisionFile);

    for rowIndex = 1:height(auditTable)
        if auditTable.gatePass(rowIndex)
            continue
        end
        targetOmega = auditTable.omegaAtMaximumInteriorDeviation(rowIndex);
        metric = string(auditTable.metricName(rowIndex));
        if metric == "A33" || metric == "B33"
            if metric == "A33"
                values = local.A33_kg;
            else
                values = local.B33_kg_s;
            end
            [covered, denseDeviation] = dense_local_deviation( ...
                local.omega_rad_s, values, targetOmega);
            auditTable.denseEvidenceMetric(rowIndex) = ...
                "dense_local_three_point_deviation";
            auditTable.denseEvidenceValue(rowIndex) = denseDeviation;
            auditTable.denseEvidenceThreshold(rowIndex) = ...
                options.maximumCurveInteriorDeviation;
            if covered && isfinite(denseDeviation) && ...
                    denseDeviation <= options.maximumCurveInteriorDeviation
                auditTable.gatePass(rowIndex) = true;
                auditTable.denseEvidenceStatus(rowIndex) = "PASS";
                auditTable.adjudicationNote(rowIndex) = ...
                    "Coarse-grid curvature resolved as dense-local continuous.";
            else
                auditTable.denseEvidenceStatus(rowIndex) = "FAIL";
                auditTable.adjudicationNote(rowIndex) = ...
                    "Dense-local coefficient continuity did not pass.";
            end
        elseif metric == "RAO3_complex"
            coversTarget = targetOmega >= min(rao.omega_rad_s) && ...
                targetOmega <= max(rao.omega_rad_s);
            maximumComplexStep = max( ...
                rao.RAO3_normalized_complex_step, [], 'omitnan');
            maximumAmplitudeStep = max( ...
                rao.RAO3_amplitude_relative_step, [], 'omitnan');
            denominatorFinite = all(isfinite(rao.D3_abs_N_per_m)) && ...
                all(rao.D3_abs_N_per_m > 0);
            physicalResonance = string( ...
                decisions.omega1p4Rao3Classification(1)) == ...
                "PHYSICAL_RESONANCE";
            auditTable.denseEvidenceMetric(rowIndex) = ...
                "max_dense_normalized_complex_step";
            auditTable.denseEvidenceValue(rowIndex) = maximumComplexStep;
            auditTable.denseEvidenceThreshold(rowIndex) = ...
                options.maximumCurveInteriorDeviation;
            if coversTarget && denominatorFinite && physicalResonance && ...
                    maximumComplexStep <= ...
                    options.maximumCurveInteriorDeviation && ...
                    maximumAmplitudeStep <= ...
                    options.maximumCurveInteriorDeviation
                auditTable.gatePass(rowIndex) = true;
                auditTable.denseEvidenceStatus(rowIndex) = "PASS";
                auditTable.adjudicationNote(rowIndex) = ...
                    "Dense complex/amplitude response is continuous; " + ...
                    "finite D3 has a physical-resonance minimum.";
            else
                auditTable.denseEvidenceStatus(rowIndex) = "FAIL";
                auditTable.adjudicationNote(rowIndex) = ...
                    "Dense RAO complex/amplitude/denominator gate did not pass.";
            end
        else
            auditTable.denseEvidenceStatus(rowIndex) = "NOT_AVAILABLE";
            auditTable.adjudicationNote(rowIndex) = ...
                "No metric-specific dense adjudication exists.";
        end
    end
    pass = all(auditTable.gatePass);
end

function [covered, deviation] = dense_local_deviation(omega, values, target)
    [distance, targetIndex] = min(abs(omega - target));
    covered = distance <= 64 * eps(max(1, abs(target))) && ...
        targetIndex > 1 && targetIndex < numel(omega);
    deviation = NaN;
    if ~covered
        return
    end
    interpolationWeight = (omega(targetIndex) - omega(targetIndex - 1)) / ...
        (omega(targetIndex + 1) - omega(targetIndex - 1));
    predicted = values(targetIndex - 1) + interpolationWeight * ...
        (values(targetIndex + 1) - values(targetIndex - 1));
    floorValue = max(1.0e-6 * max(abs(values)), eps);
    deviation = abs(values(targetIndex) - predicted) / max( ...
        [abs(values(targetIndex)), abs(predicted), floorValue]);
end

function gate = assess_formal_gate(formalTable, continuityPass, options)
% ASSESS_FORMAL_GATE Combine solve, conditioning, residual, and curve gates.

    solved = all(formalTable.status == "PASS");
    residualColumns = [formalTable.radiation_linear_relative_residual, ...
        formalTable.diffraction_linear_relative_residual, ...
        formalTable.radiation_algebraic_relative_residual, ...
        formalTable.diffraction_algebraic_relative_residual];
    maximumResidual = max(residualColumns, [], 'all', 'omitnan');
    minimumRawRcond = min(formalTable.raw_rcond, [], 'omitnan');
    minimumScaledRcond = min(formalTable.scaled_rcond, [], 'omitnan');
    logRcond = log10(formalTable.raw_rcond);
    isolatedCollapse = 0;
    for index = 2:height(formalTable) - 1
        predicted = 0.5 * (logRcond(index - 1) + logRcond(index + 1));
        isolatedCollapse = max(isolatedCollapse, predicted - logRcond(index));
    end
    conditionPass = minimumRawRcond >= options.minimumRcond && ...
        minimumScaledRcond >= options.minimumRcond && ...
        isolatedCollapse <= options.maximumIsolatedRcondCollapseDecades;
    residualPass = maximumResidual <= options.maximumRelativeResidual;
    pass = solved && conditionPass && residualPass && continuityPass;
    gate = struct('status', pass_fail(pass), ...
        'allFrequenciesSolved', solved, 'conditionPass', conditionPass, ...
        'residualPass', residualPass, 'continuityPass', continuityPass, ...
        'minimumRawRcond', minimumRawRcond, ...
        'minimumScaledRcond', minimumScaledRcond, ...
        'maximumRelativeResidual', maximumResidual, ...
        'maximumIsolatedRcondCollapseDecades', isolatedCollapse);
end

