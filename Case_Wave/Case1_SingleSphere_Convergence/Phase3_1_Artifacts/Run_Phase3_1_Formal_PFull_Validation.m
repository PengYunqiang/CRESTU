function frequencies = select_radius_screening_frequencies(formalTable, curveAudit)
% SELECT_RADIUS_SCREENING_FREQUENCIES Include extrema and curve outliers.

    solved = formalTable.status == "PASS";
    assert(all(solved), 'CRESTU:Phase31RadiusRequiresFormalPass', ...
        'Radius screening requires every formal frequency to solve first.');
    [~, peakIndex] = max(formalTable.RAO3_abs_m_per_m);
    [~, middleIndex] = min(abs(formalTable.omega_rad_s - ...
        median(formalTable.omega_rad_s)));
    [~, omega0p6Index] = min(abs(formalTable.omega_rad_s - 0.6));
    failedCurveRows = ~curveAudit.gatePass;
    suspectFrequencies = curveAudit.omegaAtMaximumInteriorDeviation( ...
        failedCurveRows);
    suspectIndices = zeros(size(suspectFrequencies));
    for suspectIndex = 1:numel(suspectFrequencies)
        [~, suspectIndices(suspectIndex)] = min(abs( ...
            formalTable.omega_rad_s - suspectFrequencies(suspectIndex)));
    end
    indices = unique([1, omega0p6Index, middleIndex, peakIndex, ...
        height(formalTable), ...
        reshape(suspectIndices, 1, [])], 'stable');
    frequencies = sort(formalTable.omega_rad_s(indices)).'; % [rad/s]
end

function [records, gate] = run_radius_screening(screeningFrequencies, ...
        formalRecords, baselineCfg, formalCfg, paths, options, force, ...
        checkpointState)
% RUN_RADIUS_SCREENING Run exact origin-radius factors and adjacent changes.

    checkpoint = fullfile(paths.artifactDirectory, ...
        'Phase3_1_Radius_Checkpoint.mat');
    radiusCheckpointFingerprint = string(sha256_hash([ ...
        char(checkpointState.combinedSHA256), '|', ...
        jsonencode(reshape(screeningFrequencies, 1, []))]));
    factors = [1.0, 1.25, 1.5];
    records = repmat(empty_record(), 0, 1);
    formalOmega = [formalRecords.omega_rad_s];
    for frequencyIndex = 1:numel(screeningFrequencies)
        [~, formalIndex] = min(abs(formalOmega - screeningFrequencies(frequencyIndex)));
        baselineRecord = formalRecords(formalIndex);
        baselineRecord.radius_factor = 1.0;
        records(end + 1, 1) = baselineRecord; %#ok<AGROW>
    end

    if ~force && isfile(checkpoint)
        loaded = load(checkpoint, 'radiusRecords', 'checkpointFingerprint');
        fingerprintMatch = isfield(loaded, 'checkpointFingerprint') && ...
            string(loaded.checkpointFingerprint) == ...
            radiusCheckpointFingerprint;
        if isfield(loaded, 'radiusRecords') && fingerprintMatch
            records = merge_pass_radius_records(records, loaded.radiusRecords);
        else
            fprintf(['[WARN] CHECKPOINT_REUSE = FORBIDDEN | radius source/', ...
                'config/geometry/frequency/runner fingerprint mismatch.\n']);
        end
    end

    for factorIndex = 2:numel(factors)
        records = run_radius_factor(records, screeningFrequencies, ...
            factors(factorIndex), formalRecords, baselineCfg, formalCfg, ...
            options, force);
        checkpointPayload = struct('radiusRecords', records, ...
            'screeningFrequencies', screeningFrequencies, ...
            'checkpointFingerprint', radiusCheckpointFingerprint, ...
            'checkpointManifest', checkpointState.manifest);
        save(checkpoint, '-struct', 'checkpointPayload');
    end
    records = calculate_radius_sensitivities(records, formalRecords, options);
    lastPass = final_radius_step_pass(records, factors(end), ...
        options.radiusRelativeTolerance);

    if ~lastPass
        fprintf(['[WARN] R->1.25R->1.5R did not meet the %.3g relative ', ...
            'tolerance; running the conditional 2R screen.\n'], ...
            options.radiusRelativeTolerance);
        records = run_radius_factor(records, screeningFrequencies, 2.0, ...
            formalRecords, baselineCfg, formalCfg, options, force);
        records = calculate_radius_sensitivities(records, formalRecords, options);
        checkpointPayload = struct('radiusRecords', records, ...
            'screeningFrequencies', screeningFrequencies, ...
            'checkpointFingerprint', radiusCheckpointFingerprint, ...
            'checkpointManifest', checkpointState.manifest);
        save(checkpoint, '-struct', 'checkpointPayload');
        lastPass = final_radius_step_pass(records, 2.0, ...
            options.radiusRelativeTolerance);
    end

    allSolved = all([records.status] == "PASS");
    if allSolved && lastPass
        status = "PASS";
    elseif allSolved
        status = "PARTIAL";
    else
        status = "FAIL";
    end
    lastFactor = max([records.radius_factor]);
    lastRows = [records.radius_factor] == lastFactor;
    finalStepSensitivities = [[records(lastRows).A33_relative_sensitivity], ...
        [records(lastRows).B33_relative_sensitivity], ...
        [records(lastRows).F3_relative_sensitivity], ...
        [records(lastRows).RAO3_relative_sensitivity]];
    comparisonRows = [records.radius_factor] > 1.0;
    allStepSensitivities = [[records(comparisonRows).A33_relative_sensitivity], ...
        [records(comparisonRows).B33_relative_sensitivity], ...
        [records(comparisonRows).F3_relative_sensitivity], ...
        [records(comparisonRows).RAO3_relative_sensitivity]];
    gate = struct('status', char(status), 'allCasesSolved', allSolved, ...
        'screeningOnly', true, 'testedFactors', unique([records.radius_factor]), ...
        'finalFactor', lastFactor, 'maximumRadiusSensitivity', ...
        max(allStepSensitivities, [], 'omitnan'), ...
        'maximumFinalStepRadiusSensitivity', ...
        max(finalStepSensitivities, [], 'omitnan'), ...
        'relativeTolerance', options.radiusRelativeTolerance, ...
        'adoptedOuterRadius', adopted_radius(status, lastFactor));
end

function records = run_radius_factor(records, screeningFrequencies, factor, ...
        formalRecords, baselineCfg, formalCfg, options, force)
% RUN_RADIUS_FACTOR Apply an exact physical top/bottom origin-radius factor.

    formalOmega = [formalRecords.omega_rad_s];
    for frequencyIndex = 1:numel(screeningFrequencies)
        omega = screeningFrequencies(frequencyIndex); % [rad/s]
        existing = abs([records.omega_rad_s] - omega) <= 64 * eps(max(1, omega)) & ...
            abs([records.radius_factor] - factor) <= 64 * eps(factor);
        if ~force && any(existing & [records.status] == "PASS")
            continue
        end
        [~, baselineIndex] = min(abs(formalOmega - omega));
        baseline = formalRecords(baselineIndex);
        wavelength = 2 * pi / baseline.physical_k_per_m; % [m]
        innerRadius = baselineCfg.fs.r_inner; % [m]
        targetTopRadius = factor * baseline.top_radius_m; % [m]
        targetBottomRadius = factor * baseline.bottom_radius_m; % [m]
        qTop = (targetTopRadius - innerRadius) / wavelength;
        qBottom = (targetBottomRadius - innerRadius) / wavelength;
        fprintf(['[INFO] Phase 3.1 radius screen | omega=%.6g rad/s ', ...
            '| factor=%.3g | q=(%.6g,%.6g)\n'], ...
            omega, factor, qTop, qBottom);
        current = run_one_production_case(omega, factor, qTop, qBottom, ...
            baselineCfg, formalCfg, options);
        if any(existing)
            records(find(existing, 1)) = current;
        else
            records(end + 1, 1) = current; %#ok<AGROW>
        end
    end
end

function merged = merge_pass_radius_records(baseline, checkpoint)
% MERGE_PASS_RADIUS_RECORDS Reuse only successful matching radius cases.

    merged = baseline;
    for index = 1:numel(checkpoint)
        candidate = checkpoint(index);
        if candidate.status ~= "PASS"
            continue
        end
        matching = abs([merged.omega_rad_s] - candidate.omega_rad_s) <= ...
            64 * eps(max(1, candidate.omega_rad_s)) & ...
            abs([merged.radius_factor] - candidate.radius_factor) <= ...
            64 * eps(max(1, candidate.radius_factor));
        if any(matching)
            merged(find(matching, 1)) = candidate;
        else
            merged(end + 1, 1) = candidate; %#ok<AGROW>
        end
    end
end

function records = calculate_radius_sensitivities(records, formalRecords, options)
% CALCULATE_RADIUS_SENSITIVITIES Compare adjacent radii with stable floors.

    AScale = max(abs([formalRecords.A33_kg]), [], 'omitnan');
    BScale = max(abs([formalRecords.B33_kg_s]), [], 'omitnan');
    FScale = max(abs(complex([formalRecords.F3_real_N_per_m], ...
        [formalRecords.F3_imag_N_per_m])), [], 'omitnan');
    RScale = max(abs(complex([formalRecords.RAO3_real_m_per_m], ...
        [formalRecords.RAO3_imag_m_per_m])), [], 'omitnan');
    floors = max(options.responseFloorFraction * [AScale, BScale, FScale, RScale], eps);
    frequencies = unique([records.omega_rad_s]);

    for frequencyIndex = 1:numel(frequencies)
        rows = find(abs([records.omega_rad_s] - frequencies(frequencyIndex)) <= ...
            64 * eps(max(1, frequencies(frequencyIndex))));
        [~, order] = sort([records(rows).radius_factor]);
        rows = rows(order);
        for localIndex = 2:numel(rows)
            previous = records(rows(localIndex - 1));
            currentIndex = rows(localIndex);
            current = records(currentIndex);
            [records(currentIndex).A33_absolute_difference_kg, ...
                records(currentIndex).A33_relative_sensitivity] = ...
                sensitivity(current.A33_kg, previous.A33_kg, floors(1));
            [records(currentIndex).B33_absolute_difference_kg_s, ...
                records(currentIndex).B33_relative_sensitivity] = ...
                sensitivity(current.B33_kg_s, previous.B33_kg_s, floors(2));
            currentF = complex(current.F3_real_N_per_m, current.F3_imag_N_per_m);
            previousF = complex(previous.F3_real_N_per_m, previous.F3_imag_N_per_m);
            [records(currentIndex).F3_absolute_difference_N_per_m, ...
                records(currentIndex).F3_relative_sensitivity] = ...
                sensitivity(currentF, previousF, floors(3));
            currentR = complex(current.RAO3_real_m_per_m, current.RAO3_imag_m_per_m);
            previousR = complex(previous.RAO3_real_m_per_m, previous.RAO3_imag_m_per_m);
            [records(currentIndex).RAO3_absolute_difference_m_per_m, ...
                records(currentIndex).RAO3_relative_sensitivity] = ...
                sensitivity(currentR, previousR, floors(4));
            records(currentIndex).A33_floor_kg = floors(1);
            records(currentIndex).B33_floor_kg_s = floors(2);
            records(currentIndex).F3_floor_N_per_m = floors(3);
            records(currentIndex).RAO3_floor_m_per_m = floors(4);
        end
    end
end

function [absoluteDifference, relativeDifference] = sensitivity(current, previous, floorValue)
% SENSITIVITY Evaluate the requested absolute and floored relative change.

    absoluteDifference = abs(current - previous);
    relativeDifference = absoluteDifference / max(abs(current), floorValue);
end

function pass = final_radius_step_pass(records, factor, tolerance)
% FINAL_RADIUS_STEP_PASS Require every screened output at the last factor.

    rows = [records.radius_factor] == factor;
    if ~any(rows) || any([records(rows).status] ~= "PASS")
        pass = false;
        return
    end
    values = [[records(rows).A33_relative_sensitivity], ...
        [records(rows).B33_relative_sensitivity], ...
        [records(rows).F3_relative_sensitivity], ...
        [records(rows).RAO3_relative_sensitivity]];
    pass = all(isfinite(values)) && max(values) <= tolerance;
end

