function summary = Run_Phase3_1_Formal_PFull_Validation(forceRecompute)
% RUN_PHASE3_1_FORMAL_PFULL_VALIDATION Run frequency and outer-radius gates.
%
% This runner keeps the Phase 2.3 production ABC and mesh-topology sources
% unchanged.  It reads the formal frequency grid from the existing
% single-sphere convergence case, uses the frozen Fine P_FULL frustum mesh
% controls, and launches one isolated production case per frequency/radius.

    arguments
        forceRecompute (1, 1) logical = false
    end

    %% Stage 1: Resolve authority, frozen gates, and production dependencies

    paths = initialize_paths();
    add_production_paths(paths);
    options = validation_options();
    frozenGate = load_frozen_phase2_3_gate(paths);
    formalCfg = read_config(paths.formalFrequencyConfig);
    baselineCfg = read_config(paths.phase2_3BaselineConfig);
    frequencies = reshape(formalCfg.freq.omegas, 1, []); % [rad/s]
    assert(numel(frequencies) == 16 && ...
        max(abs(frequencies - (0.5:0.1:2.0))) <= 64 * eps(2), ...
        'CRESTU:Phase31AuthoritativeFrequencyGrid', ...
        'The authoritative single-sphere frequency grid changed unexpectedly.');
    assert(baselineCfg.isx == 0 && baselineCfg.isy == 0 && ...
        baselineCfg.fs.nr_near == 6 && baselineCfg.fs.nr_sponge == 4 && ...
        baselineCfg.fs.nz_farfield == 4 && ...
        baselineCfg.outer_truncation.topRadiusPerWavelength == 2.0 && ...
        baselineCfg.outer_truncation.bottomRadiusPerWavelength == 1.5, ...
        'CRESTU:Phase31FrozenMeshBaseline', ...
        'The frozen Fine P_FULL Phase 2.3 mesh baseline changed unexpectedly.');
    checkpointState = build_checkpoint_state(paths, baselineCfg, ...
        formalCfg, frequencies, options);
    writetable(struct2table(checkpointState.summary), ...
        fullfile(paths.artifactDirectory, ...
        'Phase3_1_Checkpoint_Fingerprint.csv'));

    sourceBefore = production_source_snapshot(paths);
    writetable(sourceBefore, fullfile(paths.artifactDirectory, ...
        'Phase3_1_Production_Source_SHA256_Before.csv'));

    %% Stage 2: Run the formal production P_FULL frequency sweep

    formalCheckpoint = fullfile(paths.artifactDirectory, ...
        'Phase3_1_Formal_Checkpoint.mat');
    formalRecords = initialize_formal_records(frequencies, formalCheckpoint, ...
        forceRecompute, checkpointState.combinedSHA256);
    formalCsv = fullfile(paths.artifactDirectory, ...
        'Phase3_1_Formal_PFull_Frequency_Sweep.csv');

    for frequencyIndex = 1:numel(frequencies)
        if ~forceRecompute && formalRecords(frequencyIndex).status == "PASS"
            fprintf('[INFO] Reuse Phase 3.1 formal checkpoint | omega=%.6g rad/s\n', ...
                frequencies(frequencyIndex));
            continue
        end

        omega = frequencies(frequencyIndex); % [rad/s]
        fprintf('[INFO] Phase 3.1 formal sweep %d/%d | omega=%.6g rad/s\n', ...
            frequencyIndex, numel(frequencies), omega);
        formalRecords(frequencyIndex) = run_one_production_case( ...
            omega, 1.0, 2.0, 1.5, baselineCfg, formalCfg, options);
        checkpointFingerprint = checkpointState.combinedSHA256; %#ok<NASGU>
        checkpointManifest = checkpointState.manifest; %#ok<NASGU>
        save(formalCheckpoint, 'formalRecords', 'frequencies', ...
            'checkpointFingerprint', 'checkpointManifest');
        writetable(struct2table(formalRecords), formalCsv);
    end

    formalTable = struct2table(formalRecords);
    writetable(formalTable, formalCsv);
    conditionResidualTable = formalTable(:, { ...
        'omega_rad_s', 'physical_k_per_m', 'kappa_real_per_m', ...
        'kappa_imag_per_m', 'kR_top', 'kR_bottom', ...
        'raw_rcond', 'scaled_rcond', 'radiation_linear_relative_residual', ...
        'diffraction_linear_relative_residual', ...
        'radiation_algebraic_relative_residual', ...
        'diffraction_algebraic_relative_residual', 'bem_unknown_count', ...
        'assembly_runtime_s', 'total_runtime_s', 'status'});
    writetable(conditionResidualTable, fullfile(paths.artifactDirectory, ...
        'Phase3_1_Condition_Residual.csv'));

    [curveAudit, continuityPass] = audit_formal_curves(formalTable, options);
    [curveAudit, continuityPass] = adjudicate_dense_phase3_1b_evidence( ...
        curveAudit, continuityPass, paths, options);
    writetable(curveAudit, fullfile(paths.artifactDirectory, ...
        'Phase3_1_Response_Continuity_Audit.csv'));
    formalGate = assess_formal_gate(formalTable, continuityPass, options);
    phase2_3Regression = assess_phase2_3_regression( ...
        frozenGate, formalTable, paths, options);
    write_phase2_3_regression_csv(phase2_3Regression, ...
        paths.artifactDirectory);
    make_formal_figures(formalTable, paths.artifactDirectory);

    %% Stage 3: Screen exact physical outer radii at low/mid/high/peak points

    screeningFrequencies = select_radius_screening_frequencies( ...
        formalTable, curveAudit);
    [radiusRecords, radiusGate] = run_radius_screening(screeningFrequencies, ...
        formalRecords, baselineCfg, formalCfg, paths, options, ...
        forceRecompute, checkpointState);
    radiusTable = struct2table(radiusRecords);
    writetable(radiusTable, fullfile(paths.artifactDirectory, ...
        'Phase3_1_Outer_Radius_Convergence.csv'));
    make_radius_figures(radiusTable, paths.artifactDirectory);

    %% Stage 4: Verify immutable sources and persist the final report

    sourceAfter = production_source_snapshot(paths);
    sourceAfter.unchanged_during_phase3_1 = ...
        sourceAfter.sha256 == sourceBefore.sha256;
    writetable(sourceAfter, fullfile(paths.artifactDirectory, ...
        'Phase3_1_Production_Source_SHA256_After.csv'));
    productionSourcesUnchanged = all(sourceAfter.unchanged_during_phase3_1);
    assert(productionSourcesUnchanged, 'CRESTU:Phase31ProductionSourceChanged', ...
        'A frozen production ABC/mesh dependency changed during Phase 3.1.');

    summary = struct('schemaVersion', 1, ...
        'authoritativeFrequencyConfig', paths.formalFrequencyConfig, ...
        'phase2_3BaselineConfig', paths.phase2_3BaselineConfig, ...
        'frequenciesRadPerS', frequencies, ...
        'screeningFrequenciesRadPerS', screeningFrequencies, ...
        'formalTable', formalTable, 'curveAudit', curveAudit, ...
        'radiusTable', radiusTable, 'formalGate', formalGate, ...
        'radiusGate', radiusGate, ...
        'phase2_3Regression', phase2_3Regression, ...
        'checkpointState', checkpointState, ...
        'productionSourcesUnchanged', productionSourcesUnchanged, ...
        'PRODUCTION_ABC_CHANGED', 'NO', ...
        'PRODUCTION_MESH_TOPOLOGY_CHANGED', 'NO');
    save(fullfile(paths.artifactDirectory, 'Phase3_1_Validation_Result.mat'), ...
        'summary', '-v7.3');
    write_validation_report(summary, sourceAfter, paths, options);

    fprintf('[RESULT] FORMAL_FREQUENCY_SWEEP = %s\n', formalGate.status);
    fprintf('[RESULT] ALL_FREQUENCIES_SOLVED = %s\n', ...
        yes_no(formalGate.allFrequenciesSolved));
    fprintf('[RESULT] OUTER_RADIUS_CONVERGENCE = %s\n', radiusGate.status);
    fprintf('[RESULT] PHASE2_3_BASELINE_REGRESSION = %s\n', ...
        phase2_3Regression.status);
end

