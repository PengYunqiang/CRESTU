function frozenGate = load_frozen_phase2_3_gate(paths)
% LOAD_FROZEN_PHASE2_3_GATE Read, but never overwrite, the frozen evidence.

    statusCells = readcell(fullfile(paths.phase2_3ArtifactDirectory, ...
        'Phase2_3_Audit_Status.csv'), 'Delimiter', ',');
    statusTable = table(string(statusCells(2:end, 1)), ...
        string(statusCells(2:end, 2)), ...
        'VariableNames', {'status_name', 'status_value'});
    reviewerLines = readlines(fullfile(paths.phase2_3ArtifactDirectory, ...
        'Phase2_3_Reviewer_Gate.csv'));
    reviewerLines = reviewerLines(2:end);
    reviewerLines = reviewerLines(strlength(strtrim(reviewerLines)) > 0);
    reviewerScope = strings(numel(reviewerLines), 1);
    reviewerStatus = strings(numel(reviewerLines), 1);
    reviewerBlockers = zeros(numel(reviewerLines), 1);
    for lineIndex = 1:numel(reviewerLines)
        tokens = regexp(char(reviewerLines(lineIndex)), ...
            '^([^,]+),([^,]+),([^,]+),', 'tokens', 'once');
        assert(numel(tokens) == 3, 'CRESTU:Phase31ReviewerCsvShape', ...
            'Frozen reviewer CSV row %d is malformed.', lineIndex + 1);
        reviewerScope(lineIndex) = string(tokens{1});
        reviewerStatus(lineIndex) = string(tokens{2});
        reviewerBlockers(lineIndex) = str2double(tokens{3});
    end
    reviewerTable = table(reviewerScope, reviewerStatus, reviewerBlockers);
    runtimeLines = readlines(fullfile(paths.phase2_3ArtifactDirectory, ...
        'Phase2_3_Runtime_Function_Resolution.csv'));
    runtimeLines = runtimeLines(2:end);
    runtimeLines = runtimeLines(strlength(strtrim(runtimeLines)) > 0);
    runtimeFunction = strings(numel(runtimeLines), 1);
    runtimeActivePath = strings(numel(runtimeLines), 1);
    runtimeExpectedPath = strings(numel(runtimeLines), 1);
    runtimeExactMatch = false(numel(runtimeLines), 1);
    for lineIndex = 1:numel(runtimeLines)
        tokens = regexp(char(runtimeLines(lineIndex)), ...
            '^([^,]+),([^,]+),([^,]+),([^,]+)$', 'tokens', 'once');
        assert(numel(tokens) == 4, 'CRESTU:Phase31RuntimeCsvShape', ...
            'Frozen runtime-path CSV row %d is malformed.', lineIndex + 1);
        runtimeFunction(lineIndex) = string(tokens{1});
        runtimeActivePath(lineIndex) = string(tokens{2});
        runtimeExpectedPath(lineIndex) = string(tokens{3});
        runtimeExactMatch(lineIndex) = str2double(tokens{4}) == 1;
    end
    runtimeTable = table(runtimeFunction, runtimeActivePath, ...
        runtimeExpectedPath, runtimeExactMatch);
    statusPass = status_value(statusTable, 'ABC_NORMAL_LINEAGE') == "PASS" && ...
        status_value(statusTable, 'ABC_WALL_NTHETA_STATUS') == "RESOLVED" && ...
        status_value(statusTable, 'ABC_IMPLEMENTATION_ERROR') == "PASS" && ...
        status_value(statusTable, 'HANKEL_ASYMPTOTIC_ERROR_CLASSIFIED') == "YES" && ...
        status_value(statusTable, 'P_FULL_ASSEMBLY') == "PASS" && ...
        status_value(statusTable, 'OMEGA_1P5_FOCUSED_CASE') == "PASS";
    reviewerPass = all(reviewerStatus == "PASS") && ...
        sum(reviewerBlockers) == 0;
    runtimePass = all(runtimeExactMatch);
    required = statusPass && reviewerPass && runtimePass;
    assert(required, 'CRESTU:Phase31FrozenGateFailed', ...
        ['A frozen Phase 2.3 gate is not PASS: status=%d, reviewer=%d, ', ...
        'runtime=%d.'], statusPass, reviewerPass, runtimePass);
    frozenGate = struct('statusTable', statusTable, ...
        'reviewerTable', reviewerTable, 'runtimeTable', runtimeTable, ...
        'reviewerBlockers', sum(reviewerBlockers));
end

function value = status_value(statusTable, name)
% STATUS_VALUE Return exactly one named frozen status.

    row = string(statusTable{:, 1}) == string(name);
    assert(nnz(row) == 1, 'CRESTU:Phase31FrozenStatusShape', ...
        'Frozen Phase 2.3 status %s is missing or duplicated.', name);
    values = string(statusTable{:, 2});
    value = values(row);
end

function tableOut = production_source_snapshot(paths)
% PRODUCTION_SOURCE_SNAPSHOT Hash frozen ABC and topology dependencies.

    relativeFiles = [ ...
        "Source Code/2.Mesh/apply_rankine_outer_truncation.m"; ...
        "Source Code/2.Mesh/merge_domain_geometry.m"; ...
        "Source Code/4.Potential/get_rankine_outer_absorbing_bc.m"; ...
        "Source Code/4.Potential/assemble_rankine_matrix.m"; ...
        "Source Code/4.Potential/get_rankine_source_orientation.m"];
    sha = strings(size(relativeFiles));
    bytes = zeros(size(relativeFiles));
    for fileIndex = 1:numel(relativeFiles)
        filename = fullfile(paths.repositoryRoot, ...
            strrep(relativeFiles(fileIndex), '/', filesep));
        assert(isfile(filename), 'CRESTU:Phase31ProductionDependencyMissing', ...
            'Production dependency is missing: %s', filename);
        text = fileread(filename);
        sha(fileIndex) = string(sha256_hash(uint8(text)));
        info = dir(filename);
        bytes(fileIndex) = info.bytes;
    end
    tableOut = table(relativeFiles, sha, bytes, ...
        'VariableNames', {'relative_file', 'sha256', 'bytes'});
end

